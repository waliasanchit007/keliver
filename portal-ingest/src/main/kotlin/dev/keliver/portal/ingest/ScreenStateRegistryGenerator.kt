package dev.keliver.portal.ingest

/**
 * MS4-28: an app's `@ScreenState` registry (`dev.keliver.nav.ScreenStateRegistry`) as Kotlin
 * source, so a device, the editor or a test opens a named state without reflection (Kotlin/JS
 * has none for annotations).
 *
 * The registry is read with [ScreenStateRecognizer], from the files the portal's `GET /states`
 * reads (each `<screen>.kt` of the screens directory, in file-name order), and keeps the screens
 * that have states or problems: it lists the same states, in the same order, with the same
 * problems. Each entry calls its state function through an aliased import, so the generated file
 * compiles in any package of the module that declares the screens (an `internal` state function
 * included).
 */
object ScreenStateRegistryGenerator {
  const val GENERATED_HEADER: String = "// GENERATED by portal-ingest ScreenStateRegistryGenerator — do not edit."

  /** A screen file: its name (`catalog.kt`) and text. */
  data class SourceFile(val name: String, val text: String)

  /** [source] is the file's text; [screens] is what it was generated from, by screen, as `GET /states` has it. */
  data class Output(val source: String, val screens: Map<String, ScreenStates>) {
    val states: Int get() = screens.values.sumOf { it.states.size }
    val problems: List<String> get() = screens.flatMap { (screen, s) -> s.problems.map { "$screen: $it" } }
  }

  /** The screens [files] declare, by screen name, exactly as the portal's `GET /states` lists them. */
  fun read(files: List<SourceFile>): Map<String, ScreenStates> =
    files
      .filter { it.name.endsWith(".kt") }
      .sortedBy { it.name }
      .associate { it.name.removeSuffix(".kt") to ScreenStateRecognizer.recognize(it.name, it.text) }
      .filterValues { it.states.isNotEmpty() || it.problems.isNotEmpty() }

  /**
   * The registry for [files]: a `public val [valName]: ScreenStateRegistry` in [packageName]
   * ("" for the root package). [regenerateHint] is the header's second line: how to write the
   * file again.
   */
  fun generate(files: List<SourceFile>, packageName: String, valName: String, regenerateHint: String): Output {
    require(valName.matches(IDENTIFIER)) { "valName must be a Kotlin identifier: $valName" }
    require(packageName.isEmpty() || packageName.split('.').all { it.matches(IDENTIFIER) }) {
      "packageName must be a Kotlin package name: $packageName"
    }
    val screens = read(files)

    // One aliased import per state function: two screens may declare functions of the same
    // name in different packages, and an alias can't be shadowed by a name in this file.
    val aliases = HashSet<String>()
    val imports = sortedSetOf(
      "dev.keliver.nav.ExperimentalKeliverScreenStateApi",
      "dev.keliver.nav.ScreenStateRegistry",
    )
    val entries = StringBuilder()
    for ((screen, s) in screens) {
      for (state in s.states) {
        imports += "dev.keliver.nav.ScreenStateEntry"
        val base = "${identifierPart(screen)}__${identifierPart(state.function)}"
        var alias = base
        var n = 2
        while (!aliases.add(alias)) alias = "$base${n++}"
        val target = (s.packageName.split('.').filter { it.isNotEmpty() } + state.function).joinToString(".") { quote(it) }
        imports += "$target as $alias"
        entries.append("    ScreenStateEntry(\n")
        entries.append("      screen = ${literal(screen)},\n")
        entries.append("      name = ${literal(state.name)},\n")
        entries.append("      function = ${literal(state.function)},\n")
        entries.append("      routeSource = ${literal(state.route)},\n")
        entries.append("      routeType = ${state.routeType?.let(::literal) ?: "null"},\n")
        entries.append("      fixtures = ${literal(state.fixtures)},\n")
        entries.append("    ) { $alias() },\n")
      }
    }
    val problems = screens.filterValues { it.problems.isNotEmpty() }

    val source = buildString {
      appendLine(GENERATED_HEADER)
      appendLine("// $regenerateHint")
      if (packageName.isNotEmpty()) {
        appendLine("package ${packageName.split('.').joinToString(".") { quote(it) }}")
        appendLine()
      }
      imports.forEach { appendLine("import $it") }
      appendLine()
      appendLine("/**")
      appendLine(" * Every `@ScreenState` of the app's screens: the same states, in the same order and with the")
      appendLine(" * same problems, as the portal's `GET /states` lists from the same files.")
      appendLine(" */")
      appendLine("@ExperimentalKeliverScreenStateApi")
      appendLine("public val $valName: ScreenStateRegistry = ScreenStateRegistry(")
      if (entries.isEmpty()) {
        appendLine("  entries = emptyList(),")
      } else {
        appendLine("  entries = listOf(")
        append(entries)
        appendLine("  ),")
      }
      if (problems.isNotEmpty()) {
        appendLine("  problems = mapOf(")
        for ((screen, s) in problems) {
          appendLine("    ${literal(screen)} to listOf(")
          s.problems.forEach { appendLine("      ${literal(it)},") }
          appendLine("    ),")
        }
        appendLine("  ),")
      }
      appendLine(")")
    }
    return Output(source, screens)
  }

  private val IDENTIFIER = Regex("[A-Za-z_][A-Za-z0-9_]*")

  /** Kotlin's hard keywords: as a name, each needs backticks. */
  private val HARD_KEYWORDS = setOf(
    "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface",
    "is", "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias",
    "typeof", "val", "var", "when", "while",
  )

  /** [name] as Kotlin source: in backticks when it is a keyword or not a plain identifier (`` `empty cart` ``). */
  private fun quote(name: String): String =
    if (name.matches(IDENTIFIER) && name !in HARD_KEYWORDS) name else "`$name`"

  /** [name] reduced to identifier characters, for an import alias. */
  private fun identifierPart(name: String): String {
    val s = name.map { if (it.isLetterOrDigit() || it == '_') it else '_' }.joinToString("")
    return if (s.firstOrNull()?.isDigit() != false) "_$s" else s
  }

  /** [value] as a Kotlin string literal. */
  private fun literal(value: String): String = buildString {
    append('"')
    for (c in value) {
      when (c) {
        '\\' -> append("\\\\")
        '"' -> append("\\\"")
        '$' -> append("\\$")
        '\n' -> append("\\n")
        '\r' -> append("\\r")
        '\t' -> append("\\t")
        else -> append(c)
      }
    }
    append('"')
  }
}
