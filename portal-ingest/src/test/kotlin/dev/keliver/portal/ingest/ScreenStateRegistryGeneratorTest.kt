package dev.keliver.portal.ingest

import dev.keliver.portal.ingest.ScreenStateRegistryGenerator.SourceFile
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertTrue

/** MS4-28: the generated `@ScreenState` registry. */
class ScreenStateRegistryGeneratorTest {
  private val imports = "import dev.keliver.nav.NamedState\nimport dev.keliver.nav.ScreenState\n\n"

  private val catalog = SourceFile(
    "catalog.kt",
    "package app.screens\n\n" + imports + """
      @ScreenState("loaded")
      fun catalogLoaded() = NamedState(route = AppRoute.Catalog, fixtures = "catalog")

      @ScreenState("empty")
      internal fun catalogEmpty(): NamedState<AppRoute> {
        return NamedState(AppRoute.Catalog, "catalog-empty")
      }
    """.trimIndent() + "\n",
  )

  private val item = SourceFile(
    "item.kt",
    "package app.screens.item\n\n" + imports + """
      @ScreenState("detail")
      fun itemDetail() = NamedState(
        route = AppRoute.Item(id = "42", title = "a ${'$'}5 \"deal\""),
        fixtures = "item-42",
      )

      @ScreenState("hidden")
      private fun hidden() = NamedState(route = AppRoute.Item("x"), fixtures = "x")
    """.trimIndent() + "\n",
  )

  private val plain = SourceFile("plain.kt", "package app.screens\n\nfun PlainScreen() = Unit\n")

  @Test fun theRegistryListsEachStateWithAWayToRunIt() {
    val out = ScreenStateRegistryGenerator.generate(listOf(item, plain, catalog), "app.generated", "AppScreenStates", "Regenerate: run it again.")
    assertEquals(
      """
      // GENERATED by portal-ingest ScreenStateRegistryGenerator — do not edit.
      // Regenerate: run it again.
      package app.generated

      import app.screens.catalogEmpty as catalog__catalogEmpty
      import app.screens.catalogLoaded as catalog__catalogLoaded
      import app.screens.item.itemDetail as item__itemDetail
      import dev.keliver.nav.ExperimentalKeliverNavScreenStateApi
      import dev.keliver.nav.ScreenStateEntry
      import dev.keliver.nav.ScreenStateRegistry

      /**
       * Every `@ScreenState` of the app's screens: the same states, in the same order and with the
       * same problems, as the portal's `GET /states` lists from the same files.
       */
      @ExperimentalKeliverNavScreenStateApi
      public val AppScreenStates: ScreenStateRegistry = ScreenStateRegistry(
        entries = listOf(
          ScreenStateEntry(
            screen = "catalog",
            name = "loaded",
            function = "catalogLoaded",
            routeSource = "AppRoute.Catalog",
            routeType = "AppRoute.Catalog",
            fixtures = "catalog",
          ) { catalog__catalogLoaded() },
          ScreenStateEntry(
            screen = "catalog",
            name = "empty",
            function = "catalogEmpty",
            routeSource = "AppRoute.Catalog",
            routeType = "AppRoute.Catalog",
            fixtures = "catalog-empty",
          ) { catalog__catalogEmpty() },
          ScreenStateEntry(
            screen = "item",
            name = "detail",
            function = "itemDetail",
            routeSource = "AppRoute.Item(id = \"42\", title = \"a \${'$'}5 \\\"deal\\\"\")",
            routeType = "AppRoute.Item",
            fixtures = "item-42",
          ) { item__itemDetail() },
        ),
        problems = mapOf(
          "item" to listOf(
            "hidden: a state function must not be private (the generated registry calls it from another file)",
          ),
        ),
      )

      """.trimIndent(),
      out.source,
    )
    assertEquals(3, out.states)
    assertEquals(listOf("item: hidden: a state function must not be private (the generated registry calls it from another file)"), out.problems)
  }

  @Test fun itReadsWhatGetStatesReads() {
    val files = listOf(item, plain, catalog, SourceFile("notes.txt", "@ScreenState(\"x\") fun x() = 1"))
    // The screens with states or problems, by file name, each read by the portal's recognizer.
    assertEquals(
      mapOf(
        "catalog" to ScreenStateRecognizer.recognize("catalog.kt", catalog.text),
        "item" to ScreenStateRecognizer.recognize("item.kt", item.text),
      ),
      ScreenStateRegistryGenerator.read(files),
    )
    assertEquals(listOf("catalog", "item"), ScreenStateRegistryGenerator.read(files).keys.toList())
  }

  @Test fun anAppWithoutStatesGetsAnEmptyRegistry() {
    val out = ScreenStateRegistryGenerator.generate(listOf(plain), "", "Empty", "hint")
    assertEquals(
      """
      // GENERATED by portal-ingest ScreenStateRegistryGenerator — do not edit.
      // hint
      import dev.keliver.nav.ExperimentalKeliverNavScreenStateApi
      import dev.keliver.nav.ScreenStateRegistry

      /**
       * Every `@ScreenState` of the app's screens: the same states, in the same order and with the
       * same problems, as the portal's `GET /states` lists from the same files.
       */
      @ExperimentalKeliverNavScreenStateApi
      public val Empty: ScreenStateRegistry = ScreenStateRegistry(
        entries = emptyList(),
      )

      """.trimIndent(),
      out.source,
    )
  }

  @Test fun namesThatAreNotPlainIdentifiersAreQuotedAndAliasesNeverCollide() {
    val a = SourceFile(
      "a-b.kt",
      "package app.`in`\n\n$imports@ScreenState(\"one\") fun `empty cart`() = NamedState(route = Home, fixtures = \"one\")\n",
    )
    val b = SourceFile(
      "a_b.kt",
      "package other\n\n$imports@ScreenState(\"two\") fun `empty cart`() = NamedState(route = Home, fixtures = \"two\")\n",
    )
    val root = SourceFile("1st.kt", "$imports@ScreenState(\"r\") fun root() = NamedState(Home, \"r\")\n")
    val source = ScreenStateRegistryGenerator.generate(listOf(a, b, root), "gen", "S", "h").source
    assertTrue("import app.`in`.`empty cart` as a_b__empty_cart\n" in source, source)
    assertTrue("import other.`empty cart` as a_b__empty_cart2\n" in source, source)
    assertTrue("import root as _1st__root\n" in source, source)
    assertTrue("{ a_b__empty_cart() }" in source && "{ a_b__empty_cart2() }" in source, source)
  }

  /** MS4-28 review (L1): what the generated call could not compile against is a problem in the file, not an entry. */
  @Test fun aStateTheRegistryCouldNotCallIsAProblemNotAnEntry() {
    val cart = SourceFile(
      "cart.kt",
      "package app.screens\n\nimport androidx.compose.runtime.Composable\nimport app.flags.ExperimentalCheckout\n" + imports + """
        @ScreenState("drawn") @Composable fun drawn() = NamedState(route = Home, fixtures = "d")
        @ScreenState("any") fun asAny(): Any = NamedState(route = Home, fixtures = "a")
        @ScreenState("marked") @ExperimentalCheckout fun marked() = NamedState(route = Home, fixtures = "m")
        @ScreenState("ok") @OptIn(ExperimentalCheckout::class) fun ok(): NamedState<Route> = NamedState(route = Home, fixtures = "ok")
      """.trimIndent() + "\n",
    )
    val out = ScreenStateRegistryGenerator.generate(listOf(cart), "gen", "S", "h")
    assertEquals(1, out.states)
    assertTrue("import app.screens.ok as cart__ok\n" in out.source && "{ cart__ok() }" in out.source, out.source)
    for (function in listOf("drawn", "asAny", "marked")) assertTrue("cart__$function" !in out.source, function)
    val problems = out.screens.getValue("cart").problems
    assertEquals(ScreenStateRecognizer.recognize("cart.kt", cart.text).problems, problems)
    val starts = listOf(
      "drawn: a state function must not be @Composable",
      "asAny: a state function must return NamedState",
      "marked: @ExperimentalCheckout on a state function",
    )
    assertEquals(starts.size, problems.size, problems.toString())
    starts.zip(problems).forEach { (start, problem) -> assertTrue(problem.startsWith(start), problem) }
    // Each problem is in the file, as GET /states reports it (none of these needs escaping).
    problems.forEach { assertTrue("      \"$it\",\n" in out.source, it) }
  }

  @Test fun theTargetMustBeAKotlinName() {
    assertFailsWith<IllegalArgumentException> { ScreenStateRegistryGenerator.generate(emptyList(), "app", "not a name", "h") }
    assertFailsWith<IllegalArgumentException> { ScreenStateRegistryGenerator.generate(emptyList(), "app..x", "S", "h") }
  }
}
