package dev.keliver.tooling.codegen

import dev.keliver.tooling.schema.SchemaSet
import java.nio.file.Path
import kotlin.io.path.createDirectories
import kotlin.io.path.writeText

/**
 * The `--host-baseline-profile` output: Android baseline-profile rules (the human-readable form
 * AGP merges) for the HOST code the other generators write for this schema set:
 *
 * - the host protocol (`--protocol-host`): `<schema>.protocol.host` and, below it, one package per
 *   dependency schema (its protocol nodes and modifier implementations);
 * - the widget interfaces, factories and widget system (`--widget`): `<schema>.widget`, for the
 *   schema and each dependency;
 * - the modifier interfaces (`--modifier`): `<schema>.modifier`, for the schema and each dependency.
 *
 * Methods are marked hot, startup and post-startup, and the classes as startup classes, as in
 * `keliver-treehouse-host`'s own profile: a cold start applies the guest's first batch through
 * this code, and without a profile it runs in ART's interpreter while the JIT compiles it (docs/THREE_WAY_BENCHMARK.md,
 * "NF4: composed to drawn on a cold start").
 *
 * Guest code (`--compose`, `--protocol-guest`) and test code (`--testing`) are not listed: they do
 * not run in an Android host. Neither are an app's own widget implementations (they are
 * hand-written, in packages the schema does not name).
 */
internal fun SchemaSet.hostBaselineProfileRules(): List<String> {
  val methods = mutableListOf<String>()
  val classes = mutableListOf<String>()
  fun add(packagePattern: String) {
    methods += "HSPL$packagePattern;->**(**)**"
    classes += "L$packagePattern;"
  }
  // `**` here: the dependencies' protocol code sits in sub-packages of the schema's own.
  add(schema.hostProtocolPackage().toProfilePath() + "/**")
  for (schema in all) {
    // `*`: these packages have no generated sub-packages, so nothing else of the app's is caught.
    add(schema.widgetPackage().toProfilePath() + "/*")
    add(schema.modifierPackage().toProfilePath() + "/*")
  }
  return (methods + classes).distinct()
}

internal fun SchemaSet.hostBaselineProfileFileName(): String =
  "keliver-${schema.type.flatName.lowercase()}-host-baseline-prof.txt"

internal fun SchemaSet.hostBaselineProfileText(): String {
  val schemaName = schema.type.names.filter { it.isNotEmpty() }.joinToString(".")
  val schemaNames = allSchemaNames()
  val rules = hostBaselineProfileRules()
  return buildString {
    append("# Generated by keliver-tooling-codegen (--host-baseline-profile) for ")
    append(schemaName)
    append(". Do not edit.\n")
    append("# Baseline-profile rules for the generated host code of: ")
    append(schemaNames)
    append(".\n")
    for (rule in rules) {
      append(rule).append('\n')
    }
  }
}

/** Writes [hostBaselineProfileText] into [destination] (a directory, created when missing). */
internal fun SchemaSet.generateHostBaselineProfile(destination: Path) {
  destination.createDirectories()
  destination.resolve(hostBaselineProfileFileName()).writeText(hostBaselineProfileText())
}

private fun SchemaSet.allSchemaNames(): String =
  all.joinToString { it.type.names.filter { name -> name.isNotEmpty() }.joinToString(".") }

/** `com.example.schema.widget` → `com/example/schema/widget`; a schema in the root package has no leading slash. */
private fun String.toProfilePath(): String = trimStart('.').replace('.', '/')
