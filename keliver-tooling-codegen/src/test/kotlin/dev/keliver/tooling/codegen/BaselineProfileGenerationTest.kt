class BaselineProfileGenerationTest {
  @Schema(
    members = [
      Card::class,
      Pad::class,
    ],
    dependencies = [
      Dependency(1, RedwoodLayout::class),
    ],
  )
  interface HostProfileSchema

  @Widget(1)
  data class Card(@Property(1) val title: String)

  @Modifier(1)
  data class Pad(val size: Int)

  @Test fun rulesCoverTheGeneratedHostPackagesOfTheSchemaAndItsDependencies() {
    val schemaSet = parseTestSchema(HostProfileSchema::class)

    // The packages are the ones the generators write to: hostProtocolPackage(), widgetPackage()
    // and modifierPackage() (sharedHelpers.kt). The dependency's protocol code sits under the
    // schema's own protocol package, so one `**` rule covers it.
    assertThat(schemaSet.hostBaselineProfileRules()).containsExactly(
      "HSPLdev/keliver/tooling/codegen/protocol/host/**;->**(**)**",
      "HSPLdev/keliver/tooling/codegen/widget/*;->**(**)**",
      "HSPLdev/keliver/tooling/codegen/modifier/*;->**(**)**",
      "HSPLdev/keliver/layout/widget/*;->**(**)**",
      "HSPLdev/keliver/layout/modifier/*;->**(**)**",
      "Ldev/keliver/tooling/codegen/protocol/host/**;",
      "Ldev/keliver/tooling/codegen/widget/*;",
      "Ldev/keliver/tooling/codegen/modifier/*;",
      "Ldev/keliver/layout/widget/*;",
      "Ldev/keliver/layout/modifier/*;",
    )
  }

  @Test fun rulesNameTheClassesTheHostGeneratorsEmit() {
    val schemaSet = parseTestSchema(HostProfileSchema::class)
    val rules = schemaSet.hostBaselineProfileRules()
    val methodRules = rules.filter { it.startsWith("HSPL") }
      .map { Regex(it.removePrefix("HSPL").substringBefore(";").toWildcardRegex()) }

    // Every class the host-side generators produce is matched by a rule...
    val hostClasses = buildList {
      addAll(schemaSet.generateFileSpecs(ProtocolCodegenType.Host).map { it.packageName + "." + it.name })
      addAll(schemaSet.generateFileSpecs(CodegenType.Widget).map { it.packageName + "." + it.name })
      addAll(schemaSet.generateFileSpecs(CodegenType.Modifiers).map { it.packageName + "." + it.name })
    }
    for (className in hostClasses) {
      val path = className.replace('.', '/')
      assertThat(methodRules.any { it.matches(path) }, "rule for $path").isTrue()
    }

    // ...and none produced by the guest-side ones.
    val guestClasses = buildList {
      addAll(schemaSet.generateFileSpecs(ProtocolCodegenType.Guest).map { it.packageName + "." + it.name })
      addAll(schemaSet.generateFileSpecs(CodegenType.Compose).map { it.packageName + "." + it.name })
    }
    val guestClassesMatched = guestClasses.filter { className ->
      val path = className.replace('.', '/')
      methodRules.any { it.matches(path) }
    }
    assertThat(guestClassesMatched).isEmpty()
  }

  @Test fun writesOneFileTheBaselineProfilesSourceDirectoryPicksUp() {
    val schemaSet = parseTestSchema(HostProfileSchema::class)
    val out = Files.createTempDirectory("host-baseline-profile").resolve("nested")

    schemaSet.generateHostBaselineProfile(out)

    // AGP merges every file of a variant's baselineProfiles directories except startup-prof.txt.
    val file = out.resolve("keliver-baselineprofilegenerationtesthostprofileschema-host-baseline-prof.txt")
    assertThat(file.exists()).isTrue()
    val lines = file.readText().lines().filter { it.isNotEmpty() }
    assertThat(lines.first()).startsWith(
      "# Generated by keliver-tooling-codegen (--host-baseline-profile) for " +
        "dev.keliver.tooling.codegen.BaselineProfileGenerationTest.HostProfileSchema.",
    )
    assertThat(lines.filterNot { it.startsWith("#") }).isEqualTo(schemaSet.hostBaselineProfileRules())
  }
}

/** The profile's wildcards as a regex over a class path: `**` crosses `/`, `*` does not. */
private fun String.toWildcardRegex(): String = buildString {
  var i = 0
  val source = this@toWildcardRegex
  while (i < source.length) {
    when {
      source.startsWith("**", i) -> {
        append(".*")
        i += 2
      }
      source[i] == '*' -> {
        append("[^/]*")
        i += 1
      }
      else -> {
        append(Regex.escape(source[i].toString()))
        i += 1
      }
    }
  }
}
