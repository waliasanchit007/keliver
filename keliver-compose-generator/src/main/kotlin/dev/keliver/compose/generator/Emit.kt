package dev.keliver.compose.generator

const val HEADER = "// Generated by keliver-compose-generator from Compose's API and sources. Do not edit:\n" +
  "// change keliver-compose-generator/gatea.json and run :keliver-compose-generator:generateComposeApi.\n"

private val builtins = setOf("Int", "Float", "Long", "Double", "String", "Boolean", "Unit", "Any", "Nothing", "Modifier")
private val keywords = setOf("if", "else", "when", "while", "for", "return", "null", "true", "false", "this", "is", "in", "as")

/** The imports a copied default expression needs: original (`androidx.…`) or mirrored (`dev.keliver.…`). */
fun expressionImports(expr: String, decl: DeclInfo, mirror: Boolean): Set<String> = buildSet {
  for (m in Regex("""(\.?)\b([A-Za-z_][A-Za-z0-9_]*)(\s*\()?""").findAll(expr)) {
    val afterDot = m.groupValues[1] == "."
    val id = m.groupValues[2]
    val isCall = m.groupValues[3].isNotEmpty()
    val imported = decl.imports[id]
    val fq = when {
      imported != null -> imported
      afterDot || id in builtins || id in keywords -> null
      // A top-level function of the declaration's own package (`contentColorFor(color)`).
      !id.first().isUpperCase() -> if (isCall && decl.params.none { it.name == id }) "${decl.pkg}.$id" else null
      else -> "${decl.pkg}.$id"
    } ?: continue
    if (fq.startsWith("kotlin.")) continue
    add(if (mirror) mirrorFq(fq) else fq)
  }
}

/** A type as the guest writes it: mirrors, fully qualified. */
fun guestType(t: TypeRef, scopeMirror: (TypeRef) -> String = { mirrorFq(it.fq) }): String {
  val base = if (t.isFunction) {
    buildString {
      if (t.composable) append("@androidx.compose.runtime.Composable ")
      if (t.suspend) append("suspend ")
      t.receiver?.let { append(scopeMirror(it)).append('.') }
      append(t.functionParams.joinToString(", ", "(", ")") { guestType(it, scopeMirror) })
      append(" -> ").append(guestType(t.functionReturn!!, scopeMirror))
    }
  } else if (t.fq == TypeMap.IMAGE_MODEL || t.fq.startsWith("kotlin.")) {
    t.fq + if (t.args.isNotEmpty()) t.args.joinToString(", ", "<", ">") { guestType(it, scopeMirror) } else ""
  } else if (t.fq == MODIFIER) {
    "dev.keliver.compose.ui.Modifier"
  } else if (t.fq in TypeMap.generic) {
    // A generic mirror (`FiniteAnimationSpec<IntSize>`, Gate B-e) keeps its arguments.
    mirrorFq(t.fq) + t.args.joinToString(", ", "<", ">") { guestType(it, scopeMirror) }
  } else {
    // Other mirrors are not generic; a generic Compose type here is a placeholder.
    mirrorFq(t.fq)
  }
  return if (t.nullable) (if (t.isFunction) "($base)?" else "$base?") else base
}

/** The schema scope marker for a Compose scope (`RowScope` → `GenRowScope`). */
fun scopeMarker(t: TypeRef): String = "Gen" + t.simpleName

/** The values module's generated file name (not `Generated.kt`: the guest module has those in the same packages). */
const val GENERATED_DEFAULTS = "GeneratedDefaults.kt"

class Emitter(
  private val config: Config,
  private val plans: List<Plan>,
  private val factories: List<FactoryPlan> = emptyList(),
  private val defaults: DefaultsMirror? = null,
  /** A scope's Compose supertypes (`FlowRowScope` → `RowScope`), so the guest's has them too. */
  private val supertypes: (String) -> List<String> = { emptyList() },
) {
  private val generated = plans.filterIsInstance<Plan.Generated>()
  private val widgets = generated.filter { it.decl.kind == DeclKind.WIDGET }
  private val modifiers = generated.filter { it.decl.kind != DeclKind.WIDGET }

  /** The schema class a visible overload's stub sends: its own, or a hidden predecessor's with the same wire. */
  private val aliases = sentAs(generated)
  private fun sent(p: Plan.Generated): String = (aliases[p] ?: p).entry.name
  private val schemaPkg = config.schemaPackage
  private val composePkg = "$schemaPkg.compose"
  private val scopes: List<String> = (
    widgets.flatMap { w -> w.params.filter { it.kind == ParamKind.SLOT }.mapNotNull { it.param.type.receiver?.fq } } +
      modifiers.mapNotNull { m -> m.decl.owner?.let { "${m.decl.pkg}.$it" } }
    ).distinct().sorted()

  // ---------------------------------------------------------------------------------------------
  // The schema (docs/COMPOSE_GENERATOR_DESIGN.md §2)

  fun schema(): Pair<String, String> {
    val members = widgets.map { it.entry.name } + config.extras.map { "Extra$it" } + modifiers.map { it.entry.name } +
      config.extraModifiers.map { "Extra$it" }
    val body = buildString {
      append(HEADER)
      append("@file:Suppress(\"ktlint\")\n\npackage $schemaPkg\n\n")
      append("import dev.keliver.schema.Children\nimport dev.keliver.schema.Modifier\nimport dev.keliver.schema.Property\n")
      append("import dev.keliver.schema.Schema\nimport dev.keliver.schema.Schema.Dependency\nimport dev.keliver.schema.Widget\n\n")
      config.input?.let { append("// Read from: $it.\n") }
      append("/** Group `${config.group}` (lock level in keliver-compose-generator/${config.group}.lock.json). */\n")
      append("@Schema(\n  members = [\n")
      members.forEach { append("    $it::class,\n") }
      append("  ],\n  dependencies = [\n")
      config.dependencies.forEach { (tag, type) -> append("    Dependency($tag, $type::class),\n") }
      append("  ],\n)\npublic interface ${config.schemaName}\n\n")
      for (s in scopes) append("/** The schema's marker for `$s`. */\npublic object Gen${s.substringAfterLast('.')}\n\n")
      for (w in widgets) {
        append("/** `${w.decl.pkg}.${w.decl.name}`${w.decl.kdoc?.let { ": " + it.replace("*/", "* /") } ?: ""} */\n")
        append("@Widget(${w.entry.tag})\npublic data class ${w.entry.name}(\n")
        for (c in w.wire) {
          val tag = w.entry.params.getValue(c.param.name)
          val t = c.param.type
          when (c.kind) {
            ParamKind.SLOT -> append("  @Children($tag) val ${c.param.name}: ${t.receiver?.let { scopeMarker(it) + "." } ?: ""}() -> Unit,\n")
            ParamKind.LAZY -> {
              // The window of composed items (each an ExtraLazyItem) and its place in the whole list (§16).
              val n = c.param.name
              val p = w.entry.params
              append("  @Children($tag) val $n: () -> Unit,\n")
              append("  @Property(${p.getValue("$n.before")}) val ${n}Before: kotlin.Int,\n")
              append("  @Property(${p.getValue("$n.after")}) val ${n}After: kotlin.Int,\n")
              append("  @Property(${p.getValue("$n.viewport")}) val ${n}Viewport: ((kotlin.Int, kotlin.Int, kotlin.Int) -> Unit)?,\n")
            }
            ParamKind.EVENT -> append("  @Property($tag) val ${c.param.name}: ((${t.functionParams.joinToString(", ") { it.fq }}) -> Unit)?,\n")
            else -> append("  @Property($tag) val ${c.param.name}: ${TypeMap.wireType(t, t.nullable || c.defaultCase == DefaultCase.EXPRESSION)},\n")
          }
        }
        append("  @Property($MODIFIER_EVENT_TAG) val modifierEvent: ((kotlin.Int) -> Unit)? = null,\n)\n\n")
      }
      for (m in modifiers) {
        val scope = m.decl.owner?.let { ", Gen$it::class" } ?: ""
        append("/** `${m.decl.pkg}.${m.decl.owner?.let { "$it." } ?: ""}${m.decl.name}`${m.decl.kdoc?.let { ": " + it.replace("*/", "* /") } ?: ""} */\n")
        val props = modifierProps(m)
        if (props.isEmpty()) {
          append("@Modifier(${m.entry.tag}$scope)\npublic object ${m.entry.name}\n\n")
        } else {
          append("@Modifier(${m.entry.tag}$scope)\npublic data class ${m.entry.name}(\n")
          props.forEach { (name, type, default) -> append("  val $name: $type${default?.let { " = $it" } ?: ""},\n") }
          append(")\n\n")
        }
      }
    }
    return "${schemaPkg.replace('.', '/')}/Generated.kt" to body
  }

  /** A modifier's schema properties: value parameters (a case-2 one also gets `…IsDefault`), and an event's handle. */
  private fun modifierProps(m: Plan.Generated): List<Triple<String, String, String?>> = buildList {
    for (c in m.params) {
      val p = c.param
      when (c.kind) {
        ParamKind.VALUE -> {
          val literal = if (c.defaultCase == DefaultCase.LITERAL && p.defaultText in setOf("true", "false")) p.defaultText else null
          add(Triple(p.name, TypeMap.wireType(p.type, false), literal))
          if (c.defaultCase == DefaultCase.EXPRESSION) add(Triple("${p.name}IsDefault", "kotlin.Boolean", null))
        }
        ParamKind.EVENT -> add(Triple(p.name, "kotlin.Int", null))
        else -> {}
      }
    }
  }

  // ---------------------------------------------------------------------------------------------
  // Guest stubs in dev.keliver.compose.* (§4, §5)

  fun guest(): Map<String, String> {
    val files = mutableMapOf<String, StringBuilder>()
    val importsByPkg = mutableMapOf<String, MutableSet<String>>()
    fun out(pkg: String): StringBuilder = files.getOrPut(pkg) { StringBuilder() }
    fun imports(pkg: String): MutableSet<String> = importsByPkg.getOrPut(pkg) { mutableSetOf() }

    for (p in plans) {
      val d = p.decl
      if (d.kind == DeclKind.SCOPED_MODIFIER) continue // emitted inside the scope interfaces below
      val sb = out(d.mirrorPkg)
      when (p) {
        is Plan.Generated -> {
          if (p.hidden) {
            // No stub: guests cannot call it in Compose either. An ERROR-level one keeps Compose's message.
            if (d.deprecation == "ERROR") sb.append(errorStub(d, p.params, "Compose: ${d.deprecationMessage ?: "deprecated"}", imports(d.mirrorPkg)))
            continue
          }
          imports(d.mirrorPkg) += "$composePkg.${sent(p)}" + if (d.kind == DeclKind.WIDGET) "" else "Impl"
          if (d.kind == DeclKind.WIDGET) sb.append(widgetStub(p, imports(d.mirrorPkg))) else sb.append(modifierStub(p, imports(d.mirrorPkg), member = false))
          if (p.dropped.isNotEmpty()) sb.append(errorStub(d, p.params, p.dropped.joinToString(" ") { dropMessage(config, it) }, imports(d.mirrorPkg)))
        }
        is Plan.ErrorStub -> sb.append(errorStub(d, p.params, p.message, imports(d.mirrorPkg)))
      }
    }
    // Scope interfaces, with their member modifiers (RowScope.weight …).
    for (scope in scopes) {
      val pkg = mirrorPackage(packageOf(scope))
      val simple = scope.substringAfterLast('.')
      val sb = out(pkg)
      // A scope that extends another generated scope does so in the guest too (`FlowRowScope : RowScope`),
      // so its members (`Modifier.weight`) resolve; the host's real scope object is both.
      val parents = supertypes(scope).filter { it in scopes }.map { mirrorFq(it) }
      sb.append("/** The guest's `$scope`. */\n@androidx.compose.runtime.Immutable\n")
      sb.append("public interface $simple${if (parents.isEmpty()) "" else " : " + parents.joinToString(", ")} {\n")
      for (p in plans.filter { it.decl.owner == simple && "${it.decl.pkg}.$simple" == scope }) {
        when (p) {
          is Plan.Generated -> {
            if (p.hidden) continue
            imports(pkg) += "$composePkg.${sent(p)}Impl"
            sb.append(modifierStub(p, imports(pkg), member = true).prependIndent("  ")).append('\n')
            if (p.dropped.isNotEmpty()) sb.append(errorStub(p.decl, p.params, p.dropped.joinToString(" ") { dropMessage(config, it) }, imports(pkg), member = true).prependIndent("  ")).append('\n')
          }
          is Plan.ErrorStub -> sb.append(errorStub(p.decl, p.params, p.message, imports(pkg), member = true).prependIndent("  ")).append('\n')
        }
      }
      sb.append("}\n\n@PublishedApi\ninternal object ${simple}Instance : $simple\n\n")
    }
    // Placeholders for the types only error stubs name (§11).
    val placeholders = plans.flatMap { p ->
      val names = when (p) {
        is Plan.ErrorStub -> p.params
        is Plan.Generated -> p.dropped
      }.flatMap { unmappedTypes(it.param.type) }
      names
    }.distinct().sorted()
    for ((pkg, group) in placeholders.groupBy { packageOf(it) }) {
      val sb = out(mirrorPackage(pkg))
      val roots = group.map { it.removePrefix("$pkg.") }
      sb.append(placeholderClasses(roots))
    }
    // Icons (the icon group's allowlist).
    for (icon in config.icons) {
      val theme = icon.substringBeforeLast('.')
      val name = icon.substringAfterLast('.')
      val pkg = "dev.keliver.compose.material.icons." + theme.split('.').joinToString(".") { it.lowercase() }
      out(pkg).append("public val dev.keliver.compose.material.icons.Icons.$theme.$name: dev.keliver.compose.ui.graphics.vector.ImageVector\n")
        .append("  get() = dev.keliver.compose.ui.graphics.vector.ImageVector(\"$icon\")\n\n")
    }
    return files.mapKeys { (pkg, _) -> "${pkg.replace('.', '/')}/Generated.kt" }.mapValues { (path, sb) ->
      val pkg = path.substringBeforeLast('/').replace('/', '.')
      buildString {
        append(HEADER)
        append("@file:Suppress(\"ktlint\", \"RedundantVisibilityModifier\", \"UNUSED_PARAMETER\", \"unused\", \"DEPRECATION\", \"UNREACHABLE_CODE\")\n")
        if (pkg in generatedApiPkgs) append("@file:OptIn(dev.keliver.compose.wire.KeliverGeneratedApi::class)\n")
        append("\n")
        append("package $pkg\n\n")
        importsByPkg[pkg].orEmpty().filter { it.substringBeforeLast('.') != pkg }
          .sorted().forEach { append("import $it\n") }
        append('\n').append(sb)
      }
    }
  }

  private fun placeholderClasses(names: List<String>): String {
    // Nested placeholder names (`AsyncImagePainter.State.Loading`) nest inside their outer placeholders.
    class Node(val children: java.util.TreeMap<String, Node> = java.util.TreeMap())
    val root = Node()
    for (n in names) {
      var node = root
      for (part in n.split('.')) node = node.children.getOrPut(part) { Node() }
    }
    fun render(name: String, node: Node, indent: String): String = buildString {
      if (indent.isEmpty()) append("/** Placeholder: Compose's `$name` cannot reach a guest yet ($DESIGN §11). */\n")
      append("${indent}public class $name private constructor()")
      if (node.children.isEmpty()) {
        append("\n")
      } else {
        append(" {\n")
        node.children.forEach { (n, c) -> append(render(n, c, "$indent  ")) }
        append("$indent}\n")
      }
    }
    return root.children.entries.joinToString("") { (n, c) -> render(n, c, "") + "\n" }
  }

  private fun paramDecl(c: Classified, imports: MutableSet<String>, errorOverload: Boolean): String {
    val p = c.param
    val type = guestType(p.type)
    val default = when {
      !p.hasDefault -> null
      c.kind == ParamKind.DROP -> if (p.type.nullable) "null" else "TODO(\"unreachable\")"
      p.name == "modifier" -> "dev.keliver.compose.ui.Modifier"
      else -> p.defaultText!!.also { imports += expressionImports(it, c.param.let { _ -> currentDecl!! }, mirror = true) }
    }
    return "  ${p.name}: $type${default?.let { " = $it" } ?: ""},\n"
  }

  private var currentDecl: DeclInfo? = null

  /** Guest packages whose stubs use a mirror's `@KeliverGeneratedApi` members (`LazyListState.wire`). */
  private val generatedApiPkgs = mutableSetOf<String>()

  private fun widgetStub(p: Plan.Generated, imports: MutableSet<String>): String = buildString {
    val d = p.decl
    currentDecl = d
    d.kdoc?.let { append("/** ${it.replace("*/", "* /")} */\n") }
    append(deprecatedWarning(d))
    val receiver = d.widgetReceiver?.let { guestType(it) + "." } ?: ""
    append("@androidx.compose.runtime.Composable\npublic fun $receiver${d.name}(\n")
    p.params.filter { it.kind != ParamKind.DROP }.forEach { append(paramDecl(it, imports, false)) }
    append(") {\n")
    val animated = animatedParams(p)
    append(animatedPrologue(animated))
    genericWireImports(p, imports)
    val hasModifier = p.params.any { it.kind == ParamKind.MODIFIER }
    if (hasModifier) append("  val split = dev.keliver.compose.internal.splitModifierEvents(modifier)\n")
    p.params.filter { it.defaultCase == DefaultCase.EXPRESSION }.forEach {
      append("  val default_${it.param.name} = ${it.param.defaultText}\n")
    }
    for (c in p.params.filter { it.kind == ParamKind.LAZY }) {
      val state = p.lazyState ?: error("${d.spec}: a lazy list needs a LazyListState parameter")
      append("  val window_${c.param.name} = dev.keliver.compose.foundation.lazy.rememberLazyWindow(${state.param.name}, ${c.param.name})\n")
    }
    append("  ${sent(p)}(\n")
    for (c in p.wire) {
      val n = c.param.name
      when (c.kind) {
        ParamKind.SLOT -> {
          val recv = c.param.type.receiver
          append("    $n = { ${recv?.let { "${it.simpleName}Instance." } ?: ""}$n() },\n")
          recv?.let { imports += mirrorFq(it.fq) + "Instance" }
        }
        ParamKind.LAZY -> {
          // A new lambda per change of the window or its items (a memoized `{ window.Items() }` would be skipped).
          append("    $n = window_$n.items,\n")
          append("    ${n}Before = window_$n.before,\n")
          append("    ${n}After = window_$n.after,\n")
          append("    ${n}Viewport = window_$n::onViewport,\n")
        }
        ParamKind.VALUE -> when {
          c.param.type.fq == TypeMap.IMAGE_MODEL -> append("    $n = dev.keliver.compose.internal.imageModel($n),\n")
          c.explicitNull -> append("    $n = if ($n == default_$n) null else ($n ?: ${mirrorFq(c.param.type.fq)}.ExplicitNull),\n")
          c.defaultCase == DefaultCase.EXPRESSION -> append("    $n = if ($n == default_$n) null else ${TypeMap.sendExpr(c.param.type, n)},\n")
          c.param.type.fq in TypeMap.wireValue -> {
            append("    $n = $n.wire,\n")
            generatedApiPkgs += d.mirrorPkg
          }
          else -> append("    $n = ${TypeMap.sendExpr(c.param.type, n)},\n")
        }
        else -> append("    $n = $n,\n")
      }
    }
    if (hasModifier) append("    modifierEvent = split.events,\n    modifier = split.modifier${animated.joinToString("") { ".then(animated_${it.param.name})" }},\n")
    append("  )\n}\n\n")
  }

  private fun modifierStub(p: Plan.Generated, imports: MutableSet<String>, member: Boolean): String = buildString {
    val d = p.decl
    currentDecl = d
    d.kdoc?.let { append("/** ${it.replace("*/", "* /")} */\n") }
    append(deprecatedWarning(d))
    append("@androidx.compose.runtime.Stable\npublic fun dev.keliver.compose.ui.Modifier.${d.name}(\n")
    p.params.filter { it.kind != ParamKind.DROP }.forEach { append(paramDecl(it, imports, false)) }
    append("): dev.keliver.compose.ui.Modifier {\n")
    val animated = animatedParams(p)
    append(animatedPrologue(animated))
    genericWireImports(p, imports)
    val args = buildList {
      for (c in p.params) {
        val n = c.param.name
        when (c.kind) {
          ParamKind.VALUE -> if (c.defaultCase == DefaultCase.EXPRESSION) {
            append("  val default_$n = ${c.param.defaultText}\n")
            add("$n = ${TypeMap.sendExpr(c.param.type, n)}")
            add("${n}IsDefault = $n == default_$n")
          } else {
            add("$n = ${TypeMap.sendExpr(c.param.type, n)}")
          }
          ParamKind.EVENT -> add("$n = handle")
          else -> {}
        }
      }
    }
    val impl = "${sent(p)}Impl"
    val construct = if (args.isEmpty()) impl else "$impl(${args.joinToString(", ")})"
    val event = p.params.firstOrNull { it.kind == ParamKind.EVENT }
    // An animated reference travels as an `ExtraAnimated` element just before the element it animates.
    val before = animated.joinToString("") { "then(animated_${it.param.name})." }
    if (event != null) {
      append("  return ${before}then(dev.keliver.compose.internal.ModifierEventElement(${event.param.name}) { handle -> $construct })\n}\n")
    } else {
      append("  return ${before}then($construct)\n}\n")
    }
  }

  /** The Float, Dp and Color parameters of a declaration configured as `animated` (Gate B-e). */
  private fun animatedParams(p: Plan.Generated): List<Classified> =
    if (p.decl.spec !in config.animated) {
      emptyList()
    } else {
      p.params.filter { it.kind == ParamKind.VALUE && it.param.type.fq in TypeMap.animatable && !it.param.type.nullable }
    }

  /**
   * A stub's first lines for its animated parameters: the `ExtraAnimated` element a tagged value
   * carries (or an empty modifier), then the parameter shadowed by its exact target.
   */
  /** The `.wire` extension a generic wire type's stub calls (`FiniteAnimationSpec<…>.wire`). */
  private fun genericWireImports(p: Plan.Generated, imports: MutableSet<String>) {
    if (p.params.any { it.kind == ParamKind.VALUE && it.param.type.fq in TypeMap.generic }) imports += "dev.keliver.compose.animation.core.wire"
  }

  private fun animatedPrologue(animated: List<Classified>): String = buildString {
    for (c in animated) {
      val n = c.param.name
      append("  val animated_$n = dev.keliver.compose.internal.animated(\"$n\", $n)\n")
      append("  @Suppress(\"NAME_SHADOWING\") val $n = dev.keliver.compose.internal.untag($n)\n")
    }
  }

  /** Compose's own WARNING-level deprecation, copied so a guest sees the same warning. */
  private fun deprecatedWarning(d: DeclInfo): String =
    if (d.deprecation == "WARNING") "@Deprecated(${kotlinString("Compose: " + (d.deprecationMessage ?: "deprecated"))})\n" else ""

  private fun errorStub(d: DeclInfo, params: List<Classified>, message: String, imports: MutableSet<String>, member: Boolean = false): String = buildString {
    currentDecl = d
    append("@Deprecated(${kotlinString(message)}, level = DeprecationLevel.ERROR)\n")
    val receiver = d.receiver?.let { guestType(it) + "." } ?: ""
    if (d.kind == DeclKind.WIDGET) append("@androidx.compose.runtime.Composable\n")
    append("public fun $receiver${d.name}(\n")
    params.forEach { append(paramDecl(it, imports, true)) }
    append("): ${if (d.returns.fq == "kotlin.Unit") "Unit" else guestType(d.returns)} = throw UnsupportedOperationException(${kotlinString(message)})\n\n")
  }

  // ---------------------------------------------------------------------------------------------
  // Host renderers (§8, §9)

  fun host(): Pair<String, String> {
    val hostPkg = "$schemaPkg.composeui"
    val imports = sortedSetOf<String>()
    val body = StringBuilder()
    for (w in widgets) {
      val d = w.decl
      val cls = "ComposeUi${w.entry.name}"
      imports += "$schemaPkg.widget.${w.entry.name}"
      body.append(
        if (w.hidden) {
          "/** A hidden overload of `${d.pkg}.${d.name}` (kept for guests built before it was hidden): calls the visible one. */\n"
        } else {
          "/** Calls the real `${d.pkg}.${d.name}`. */\n"
        },
      )
      body.append("internal class $cls : ${w.entry.name}<@Composable (Modifier) -> Unit>, GeneratedWidget {\n")
      body.append("  override var modifier: KeliverModifier by mutableStateOf<KeliverModifier>(KeliverModifier)\n")
      body.append("  override var modifierEventSink: ((Int) -> Unit)? = null\n")
      for (c in w.wire) {
        val n = c.param.name
        when (c.kind) {
          ParamKind.SLOT -> body.append("  override val $n: ScopedChildren = ScopedChildren()\n")
          ParamKind.LAZY -> {
            body.append("  override val $n: ScopedChildren = ScopedChildren()\n")
            body.append("  private var p_${n}Before: Any? by mutableStateOf<Any?>(0)\n")
            body.append("  override fun ${n}Before(${n}Before: kotlin.Int) { p_${n}Before = ${n}Before }\n")
            body.append("  private var p_${n}After: Any? by mutableStateOf<Any?>(0)\n")
            body.append("  override fun ${n}After(${n}After: kotlin.Int) { p_${n}After = ${n}After }\n")
            body.append("  private var p_${n}Viewport: ((kotlin.Int, kotlin.Int, kotlin.Int) -> Unit)? = null\n")
            body.append("  override fun ${n}Viewport(${n}Viewport: ((kotlin.Int, kotlin.Int, kotlin.Int) -> Unit)?) { p_${n}Viewport = ${n}Viewport }\n")
          }
          ParamKind.EVENT -> {
            body.append("  private var p_$n: Any? by mutableStateOf<Any?>(null)\n")
            val lt = "(${c.param.type.functionParams.joinToString(", ") { it.fq }}) -> Unit"
            body.append("  override fun $n($n: ($lt)?) { p_$n = $n }\n")
          }
          else -> {
            // A parameter with a default starts as "not sent" (null): a guest built before this
            // parameter travelled never sends it, and the renderer then uses Compose's default.
            body.append("  private var p_$n: Any? by mutableStateOf<Any?>(${if (c.param.hasDefault) "null" else "Unset"})\n")
            body.append("  override fun $n($n: ${TypeMap.wireType(c.param.type, c.param.type.nullable || c.defaultCase == DefaultCase.EXPRESSION)}) { p_$n = $n }\n")
          }
        }
      }
      body.append("  override fun modifierEvent(modifierEvent: ((Int) -> Unit)?) { modifierEventSink = modifierEvent }\n")
      val required = w.wire.filter { it.kind == ParamKind.VALUE && !it.param.hasDefault }
      body.append("  override val value: @Composable (Modifier) -> Unit = { incoming ->\n")
      if (required.isNotEmpty()) body.append("    if (${required.joinToString(" && ") { "p_${it.param.name} !== Unset" }}) {\n") else body.append("    run {\n")
      // Locals in Compose's order, so a default that names an earlier parameter (`fallback = error`) reads it.
      // A hidden overload passes only what its visible successor takes; Compose defaults the rest.
      val animated = animatedParams(w)
      if (animated.isNotEmpty()) body.append("      val animatedRefs = modifier.trailingAnimated()\n")
      for (c in w.called) {
        var line = hostLocal(c, d, imports) ?: continue
        if (c in animated) {
          // The guest's animated reference (`animate*AsState`): the real one runs here (Gate B-e).
          val n = c.param.name
          line = "val $n = (" + line.removePrefix("val $n = ") + ").animated(animatedRefs, \"$n\")"
        }
        body.append("      $line\n")
      }
      body.append("      ${d.pkg}.${d.name}(\n")
      for (c in w.called) {
        val n = c.param.name
        when (c.kind) {
          ParamKind.MODIFIER -> body.append("        $n = incoming.applyGenerated(modifier, this@$cls),\n")
          ParamKind.SLOT -> body.append("        $n = { this@$cls.$n.Render(${if (c.param.type.receiver != null) "this" else "null"}) },\n")
          ParamKind.LAZY -> body.append("        $n = { lazyWindow(this@$cls.$n, p_${n}Before as Int, p_${n}After as Int) },\n")
          ParamKind.VALUE, ParamKind.EVENT -> body.append("        $n = $n,\n")
          else -> {}
        }
      }
      body.append("      )\n")
      for (c in w.called.filter { it.kind == ParamKind.LAZY }) {
        val n = c.param.name
        body.append("      ReportLazyViewport(${w.lazyState!!.param.name}) { first, last, offset -> p_${n}Viewport?.invoke(first, last, offset) }\n")
      }
      body.append("    }\n  }\n}\n\n")
    }
    // The factory.
    body.append("/** The generated widgets' factory; extras (hand-written) are the only hand-written renderers. */\n")
    body.append("public class ComposeUi${config.schemaName}WidgetFactory : ${config.schemaName}WidgetFactory<@Composable (Modifier) -> Unit> {\n")
    imports += "$schemaPkg.widget.${config.schemaName}WidgetFactory"
    for (w in widgets) body.append("  override fun ${w.entry.name}(): ${w.entry.name}<@Composable (Modifier) -> Unit> = ComposeUi${w.entry.name}()\n")
    for (e in config.extras) {
      imports += "$schemaPkg.widget.Extra$e"
      body.append("  override fun Extra$e(): Extra$e<@Composable (Modifier) -> Unit> = ComposeUiExtra$e()\n")
    }
    // Redwood's factory hook for unscoped modifiers: generated widgets apply their own (applyGenerated).
    for (mod in modifiers.filter { it.decl.kind == DeclKind.MODIFIER }) {
      body.append("  override fun ${mod.entry.name}(value: @Composable (Modifier) -> Unit, modifier: ${mod.entry.name}) {}\n")
    }
    for (e in config.extraModifiers) {
      imports += "$schemaPkg.modifier.Extra$e"
      body.append("  override fun Extra$e(value: @Composable (Modifier) -> Unit, modifier: Extra$e) {}\n")
    }
    body.append("}\n\n")
    // Modifiers.
    val anyAnimated = config.animated.isNotEmpty()
    body.append("/** Applies a generated widget's own (unscoped) generated modifiers, in the guest's order. */\n")
    body.append("@Composable\ninternal fun Modifier.applyGenerated(chain: KeliverModifier, owner: GeneratedWidget?): Modifier {\n")
    body.append("  val elements = ArrayList<KeliverModifier.UnscopedElement>()\n  chain.forEachUnscoped { elements += it }\n  var m = this\n")
    if (anyAnimated) {
      // Gate B-e: `ExtraAnimated` elements name parameters of the element that follows them.
      body.append("  var pending: List<ExtraAnimated> = emptyList()\n")
      body.append("  for (e in elements) {\n")
      body.append("    if (e is ExtraAnimated) {\n      pending = pending + e\n      continue\n    }\n")
      body.append("    m = when (e) {\n")
    } else {
      body.append("  for (e in elements) {\n    m = when (e) {\n")
    }
    for (mod in modifiers.filter { it.decl.kind == DeclKind.MODIFIER }) {
      imports += "$schemaPkg.modifier.${mod.entry.name}"
      body.append("      is ${mod.entry.name} -> ${modifierCall(mod, "m", imports)}\n")
    }
    body.append("      else -> m\n    }\n")
    if (anyAnimated) body.append("    pending = emptyList()\n")
    body.append("  }\n  return m\n}\n\n")
    body.append("/** Applies a child's scoped modifiers with its parent's real scope as receiver (§9). */\n")
    body.append("@Composable\ninternal fun Modifier.applyScoped(chain: KeliverModifier, scope: Any?): Modifier {\n")
    body.append("  val elements = ArrayList<KeliverModifier.ScopedElement>()\n  chain.forEachScoped { elements += it }\n  var m = this\n")
    body.append("  for (e in elements) {\n    m = when {\n")
    for (mod in modifiers.filter { it.decl.kind == DeclKind.SCOPED_MODIFIER }) {
      imports += "$schemaPkg.modifier.${mod.entry.name}"
      val scope = "${mod.decl.pkg}.${mod.decl.owner}"
      body.append("      e is ${mod.entry.name} && scope is $scope -> with(scope) { ${modifierCall(mod, "m", imports)} }\n")
    }
    body.append("      else -> m\n    }\n  }\n  return m\n}\n\n")
    // `*Defaults`.
    body.append(hostDefaults(imports))
    imports += "dev.keliver.compose.wire.arg"
    // Icons.
    body.append("/** The icon group's allowlist: the host resolves a guest's icon by name. */\n")
    body.append("internal fun iconByName(name: String): androidx.compose.ui.graphics.vector.ImageVector? = when (name) {\n")
    for (icon in config.icons) {
      val theme = icon.substringBeforeLast('.')
      val n = icon.substringAfterLast('.')
      body.append("  \"$icon\" -> androidx.compose.material.icons.Icons.$theme.$n\n")
      imports += "androidx.compose.material.icons.${theme.split('.').joinToString(".") { it.lowercase() }}.$n"
    }
    body.append("  else -> null\n}\n")

    val text = buildString {
      append(HEADER)
      append("@file:Suppress(\"ktlint\", \"UNCHECKED_CAST\", \"RedundantVisibilityModifier\", \"DEPRECATION\")\n")
      // Generated renderers call experimental Compose API (TopAppBar) on the guest's behalf.
      append("@file:OptIn(androidx.compose.material3.ExperimentalMaterial3Api::class)\n\n")
      append("package $hostPkg\n\n")
      val fixed = listOf(
        "androidx.compose.runtime.Composable",
        "androidx.compose.runtime.getValue",
        "androidx.compose.runtime.mutableStateOf",
        "androidx.compose.runtime.setValue",
        "androidx.compose.ui.Modifier",
        "dev.keliver.Modifier as KeliverModifier",
      )
      (fixed + imports).distinct().sorted().forEach { append("import $it\n") }
      append('\n').append(body)
    }
    return "${hostPkg.replace('.', '/')}/Generated.kt" to text
  }

  /** A widget renderer's local for one parameter: the decoded value, or Compose's default when not sent. */
  private fun hostLocal(c: Classified, d: DeclInfo, imports: MutableSet<String>): String? {
    val n = c.param.name
    val t = c.param.type
    return when (c.kind) {
      ParamKind.VALUE -> {
        val sentNullable = t.nullable || c.defaultCase == DefaultCase.EXPRESSION
        val wt = TypeMap.wireType(t, sentNullable)
        val plain = t.fq == TypeMap.IMAGE_MODEL || TypeMap.isPrimitive(t)
        val default = c.param.defaultText
        if (default != null && c.defaultCase != DefaultCase.NONE) imports += expressionImports(default, d, mirror = false)
        val conv = hostConversion(t)
        when {
          c.explicitNull ->
            // A factory-made value from a factory this host does not know is null: Compose's default.
            "val $n = (p_$n as $wt).let { v -> if (v == null) $default else if (v.isExplicitNull()) null else v.$conv${if (t.fq in TypeMap.opaque) " ?: $default" else ""} }"
          c.defaultCase == DefaultCase.EXPRESSION -> "val $n = (p_$n as $wt)${if (plain) "" else "?.$conv"} ?: $default"
          c.defaultCase == DefaultCase.LITERAL -> {
            val nwt = if (wt.endsWith("?")) wt else "$wt?"
            "val $n = (p_$n as $nwt)${if (plain) "" else "?.$conv"}${if (default == "null") "" else " ?: $default"}"
          }
          else -> "val $n = (p_$n as $wt)${if (plain) {
            ""
          } else if (wt.endsWith("?")) {
            "?.$conv"
          } else {
            ".$conv"
          }}"
        }
      }
      ParamKind.EVENT -> "val $n = (p_$n as ((${t.functionParams.joinToString(", ") { it.fq }}) -> Unit)?)" +
        if (t.nullable) "" else " ?: {${if (t.functionParams.isEmpty()) "" else " _ -> "}}"
      else -> null
    }
  }

  /** The host's conversion of a sent value: `toCompose()`, typed for a generic wire type (`toCompose<IntSize>()`). */
  private fun hostConversion(t: TypeRef): String =
    if (t.fq in TypeMap.generic) "toCompose<${t.args.joinToString(", ") { it.fq }}>()" else "toCompose()"

  private fun modifierCall(mod: Plan.Generated, receiver: String, imports: MutableSet<String>): String {
    val d = mod.decl
    val args = mutableListOf<String>()
    val locals = mutableListOf<String>()
    val animated = animatedParams(mod)
    for (c in mod.called) {
      val n = c.param.name
      val t = c.param.type
      when (c.kind) {
        ParamKind.VALUE -> {
          val conv = if (TypeMap.isPrimitive(t)) "" else "." + hostConversion(t)
          // The guest's animated reference (`animate*AsState`) runs here, as the real one (Gate B-e).
          val anim = if (c in animated) ".animated(pending, \"$n\")" else ""
          if (c.defaultCase == DefaultCase.EXPRESSION) {
            imports += expressionImports(c.param.defaultText!!, d, mirror = false)
            locals += "val $n = (if (e.${n}IsDefault) ${c.param.defaultText} else e.$n$conv)$anim"
          } else {
            locals += "val $n = e.$n$conv$anim"
          }
          args += "$n = $n"
        }
        ParamKind.EVENT -> {
          locals += "val handle = e.$n"
          args += "$n = { owner?.modifierEventSink?.invoke(handle) }"
        }
        else -> {}
      }
    }
    val call = "$receiver.${d.name}(${args.joinToString(", ")})"
    if (d.kind == DeclKind.MODIFIER) imports += "${d.pkg}.${d.name}"
    return if (locals.isEmpty()) call else "run { ${locals.joinToString("; ")}; $call }"
  }

