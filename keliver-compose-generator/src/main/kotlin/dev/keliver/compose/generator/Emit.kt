  // `*Defaults` mirrors (§5–§7), written into keliver-compose-values: the schema names their types.

  fun values(): Map<String, String> {
    val members = defaults?.all.orEmpty()
    val files = sortedMapOf<String, StringBuilder>()
    val importsByPkg = mutableMapOf<String, MutableSet<String>>()
    fun out(pkg: String) = files.getOrPut(pkg) { StringBuilder() }
    // The types only factories make.
    for (fq in TypeMap.opaque.filter { t -> factories.any { it.decl.returns.fq == t } }) {
      val simple = fq.substringAfterLast('.')
      val makers = factories.filter { it.decl.returns.fq == fq }.map { "${it.decl.owner}.${it.decl.name}" }.distinct()
      out(mirrorPackage(packageOf(fq))).append(
        """
        |/** Compose's `$fq`, made only by ${makers.joinToString { "`$it`" }}: the call, made by the host. */
        |@androidx.compose.runtime.Immutable
        |@kotlinx.serialization.Serializable(with = $simple.Codec::class)
        |public class $simple(call: dev.keliver.compose.wire.DefaultsCall) : dev.keliver.compose.wire.DefaultsValue(call) {
        |  public object Codec : dev.keliver.compose.wire.DefaultsValueCodec<$simple>("${mirrorFq(fq)}", ::$simple)
        |
        |  public companion object {
        |    /** An explicit `null` where the parameter's default is not null. */
        |    public val ExplicitNull: $simple = $simple(dev.keliver.compose.wire.DefaultsCall.ExplicitNull)
        |  }
        |}
        |
        |
        """.trimMargin(),
      )
    }
    // The objects, with the members the generated API names.
    for ((ownerFq, group) in members.groupBy { it.ownerFq }.toSortedMap()) {
      val pkg = mirrorPackage(packageOf(ownerFq))
      val simple = ownerFq.substringAfterLast('.')
      val imports = importsByPkg.getOrPut(pkg) { sortedSetOf() }
      val sb = out(pkg)
      sb.append("/** The guest's `$ownerFq`: the members the generated API names (design §5–§7). */\npublic object $simple {\n")
      for (m in group.sortedBy { it.name }) {
        when (m) {
          is DefaultsMirror.Member.Reference -> {
            val (type, value) = when (m.type.fq) {
              "androidx.compose.ui.graphics.Color" -> "dev.keliver.compose.ui.graphics.Color" to "dev.keliver.compose.ui.graphics.Color.reference(\"$simple.${m.name}\")"
              else -> "dev.keliver.compose.ui.graphics.Shape" to "dev.keliver.compose.ui.graphics.ShapeReference.of(\"$simple.${m.name}\")"
            }
            sb.append("  /** A reference: the host reads `$simple.${m.name}` where the widget renders. */\n")
            sb.append("  public val ${m.name}: $type\n    @androidx.compose.runtime.Composable\n    get() = $value\n\n")
          }
          is DefaultsMirror.Member.Snapshot -> {
            sb.append("  /** Compose's value when this was generated${config.input?.let { " ($it)" } ?: ""}. */\n")
            sb.append("  public val ${m.name}: ${guestType(m.type)} = ${m.literal}\n\n")
          }
          is DefaultsMirror.Member.Factory -> for (f in factories.filter { it.decl.owner == simple && it.decl.name == m.name && "${it.decl.pkg}.${it.decl.owner}" == ownerFq }) {
            sb.append(factoryStub(f, imports).prependIndent("  ")).append("\n\n")
          }
          is DefaultsMirror.Member.Unsupported -> {
            val message = "Keliver: `$simple.${m.name}`: ${m.reason} ($DESIGN §5)."
            sb.append("  @Deprecated(${kotlinString(message)}, level = DeprecationLevel.ERROR)\n")
            if (m.call) {
              sb.append("  public fun ${m.name}(vararg args: Any?): Nothing = throw UnsupportedOperationException(${kotlinString(message)})\n\n")
            } else {
              sb.append("  public val ${m.name}: Nothing\n    get() = throw UnsupportedOperationException(${kotlinString(message)})\n\n")
            }
          }
        }
      }
      sb.setLength(sb.length - 1)
      sb.append("}\n\n")
    }
    return files.mapKeys { (pkg, _) -> "${pkg.replace('.', '/')}/$GENERATED_DEFAULTS" }.mapValues { (path, sb) ->
      val pkg = path.substringBeforeLast('/').replace('/', '.')
      buildString {
        append(HEADER)
        append("@file:Suppress(\"ktlint\", \"RedundantVisibilityModifier\", \"UNUSED_PARAMETER\", \"unused\")\n\n")
        append("package $pkg\n\n")
        importsByPkg[pkg].orEmpty().filter { it.substringBeforeLast('.') != pkg }.forEach { append("import $it\n") }
        append('\n').append(sb.toString().trimEnd()).append('\n')
      }
    }
  }

  private fun factoryStub(f: FactoryPlan, imports: MutableSet<String>): String = buildString {
    val d = f.decl
    currentDecl = d
    d.kdoc?.let { append("/** ${it.replace("*/", "* /")} */\n") }
    if (f.error != null) append("@Deprecated(${kotlinString(f.error)}, level = DeprecationLevel.ERROR)\n")
    if (d.isComposable) append("@androidx.compose.runtime.Composable\n")
    append("public fun ${d.name}(\n")
    for (c in f.params) {
      val default = f.guestDefaults[c.param.name]?.also { imports += expressionImports(it, d, mirror = true) }
      append("  ${c.param.name}: ${guestType(c.param.type)}${default?.let { " = $it" } ?: ""},\n")
    }
    val ret = guestType(d.returns)
    if (f.error != null) {
      append("): $ret = throw UnsupportedOperationException(${kotlinString(f.error)})")
      return@buildString
    }
    val make = if (d.returns.fq in TypeMap.opaque) ret else "$ret.ofCall"
    if (f.params.isEmpty()) {
      append("): $ret = $make(dev.keliver.compose.wire.DefaultsCall(${f.entry!!.tag}))")
      return@buildString
    }
    // Only the arguments that differ from their defaults travel; the host evaluates the rest (§5).
    append("): $ret {\n  val args = LinkedHashMap<Int, kotlinx.serialization.json.JsonElement>()\n")
    for (c in f.params) {
      val n = c.param.name
      val put = "args[${f.entry!!.params.getValue(n)}] = dev.keliver.compose.wire.defaultsArg($n)"
      val default = f.guestDefaults[n]
      append(if (default == null) "  $put\n" else "  if ($n != ($default)) $put\n")
    }
    append("  return $make(dev.keliver.compose.wire.DefaultsCall(${f.entry!!.tag}, args))\n}")
  }

  /** The host half: each factory-made type calls the real factory; references resolve by name. */
  private fun hostDefaults(imports: MutableSet<String>): String = buildString {
    val made = factories.filter { it.error == null }
    for (fq in TypeMap.opaque.filter { t -> made.any { it.decl.returns.fq == t } }) {
      append("/** Makes the guest's recorded `${fq.substringAfterLast('.')}` by calling the real factory. */\n")
      // Null for a factory appended after this host was built (a newer guest): reported once, and the
      // parameter then takes Compose's own default where it renders (a TextButton's colours are
      // `textButtonColors()`), as an unknown icon renders a placeholder. Never a crash in composition.
      append("@Composable\ninternal fun ${mirrorFq(fq)}.toCompose(): $fq? = when (call.factory) {\n")
      for (f in made.filter { it.decl.returns.fq == fq }) append("  ${f.entry!!.tag} -> ${factoryCall(f, imports)}\n")
      append("  else -> { reportMismatchOnce(\"${fq.substringAfterLast('.')}: unknown factory \${call.factory}; Compose's default instead\"); null }\n}\n\n")
    }
    append("/** A border the guest recorded as a `*Defaults` factory call, made by the real factory. */\n")
    append("@Composable\ninternal fun defaultsBorderStroke(call: dev.keliver.compose.wire.DefaultsCall): androidx.compose.foundation.BorderStroke? = when (call.factory) {\n")
    for (f in made.filter { it.decl.returns.fq == "androidx.compose.foundation.BorderStroke" }) append("  ${f.entry!!.tag} -> ${factoryCall(f, imports)}\n")
    append("  else -> null\n}\n\n")
    val refs = defaults?.all.orEmpty().filterIsInstance<DefaultsMirror.Member.Reference>()
    for ((kind, fq) in listOf("Color" to "androidx.compose.ui.graphics.Color", "Shape" to "androidx.compose.ui.graphics.Shape")) {
      append("/** A `*Defaults` ${kind.lowercase()} the guest referred to by name, read where the widget renders. */\n")
      append("@Composable\ninternal fun defaults$kind(name: String): $fq? = when (name) {\n")
      for (r in refs.filter { it.type.fq == fq }) append("  \"${r.ownerFq.substringAfterLast('.')}.${r.name}\" -> ${r.ownerFq}.${r.name}\n")
      append("  else -> null\n}\n\n")
    }
  }

  /**
   * The host's call of the real factory: each argument the guest recorded, or Compose's own default
   * expression for one it left out, evaluated in parameter order (a default may read an earlier one).
   */
  private fun factoryCall(f: FactoryPlan, imports: MutableSet<String>): String {
    if (f.params.isEmpty()) return "${f.decl.pkg}.${f.decl.owner}.${f.decl.name}()"
    val locals = f.params.joinToString("; ") { c ->
      val t = c.param.type
      val n = c.param.name
      val read = "call.arg<${TypeMap.wireType(t, false)}>(${f.entry!!.params.getValue(n)})" +
        if (TypeMap.isPrimitive(t)) "" else "?.toCompose()"
      val default = f.hostDefaults[n]?.also { imports += expressionImports(it, f.decl, mirror = false) }
      "val $n = $read ?: ${default ?: "error(\"${f.decl.owner}.${f.decl.name}: '$n' not sent\")"}"
    }
    val args = f.params.joinToString(", ") { "${it.param.name} = ${it.param.name}" }
    return "run { $locals; ${f.decl.pkg}.${f.decl.owner}.${f.decl.name}($args) }"
  }

  // ---------------------------------------------------------------------------------------------
  // Editor metadata (§13)

  fun editor(): String = buildString {
    // Hidden overloads have no stub, so nothing in a screen can name them: not in the palette.
    append("{\n  \"group\": \"${config.group}\",\n  \"widgets\": [\n")
    append(widgets.filter { !it.hidden }.joinToString(",\n") { w -> entryJson(w) })
    append("\n  ],\n  \"modifiers\": [\n")
    append(modifiers.filter { !it.hidden }.joinToString(",\n") { m -> entryJson(m) })
    append("\n  ]\n}\n")
  }

  /**
   * One declaration's editor metadata. ED0 (docs/ED0_SPIKE.md) reads it to recognise Compose-shaped
   * calls: every parameter in Compose's order (the `modifier` one too, so positional arguments map),
   * each value parameter's guest type, nullability, a slot's scope and whether it is optional, and
   * the guest's fully qualified name and a scoped modifier's scope (resolution by import and scope).
   */
  private fun entryJson(p: Plan.Generated): String = buildString {
    val d = p.decl
    append("    {\"name\": \"${d.name}\", \"compose\": \"${d.pkg}.${d.owner?.let { "$it." } ?: ""}${d.name}\", ")
    append("\"guest\": \"${d.mirrorPkg}.${d.owner?.let { "$it." } ?: ""}${d.name}\", ")
    d.owner?.let { append("\"scope\": \"${mirrorPackage(d.pkg)}.$it\", ") }
    append("\"palette\": \"${d.pkg}\", \"tag\": ${p.entry.tag}, \"schemaClass\": \"${p.entry.name}\", ")
    d.kdoc?.let { append("\"doc\": ${jsonString(it)}, ") }
    append("\"params\": [")
    append(
      p.params.joinToString(", ") { c ->
        val t = c.param.type
        val kind = when (c.kind) {
          ParamKind.MODIFIER -> "modifier"
          ParamKind.SLOT -> "slot"
          ParamKind.LAZY -> "lazy-content"
          ParamKind.EVENT -> "event"
          ParamKind.DROP, ParamKind.BLOCK -> "unsupported"
          else -> t.simpleName.replaceFirstChar { it.lowercase() }
        }
        buildString {
          append("{\"name\": \"${c.param.name}\", \"kind\": \"$kind\"")
          if (c.kind == ParamKind.VALUE) append(", \"type\": \"${if (t.fq.startsWith("kotlin.")) t.fq else mirrorFq(t.fq)}\"")
          if (c.kind == ParamKind.SLOT) t.receiver?.let { append(", \"scope\": \"${mirrorFq(it.fq)}\"") }
          if (c.kind == ParamKind.SLOT && (c.param.hasDefault || t.nullable)) append(", \"optional\": true")
          if (t.nullable && c.kind != ParamKind.SLOT) append(", \"nullable\": true")
          if (c.kind != ParamKind.MODIFIER) {
            c.param.defaultText?.let { append(", \"default\": ${jsonString(it)}, \"defaultCase\": \"${c.defaultCase.name.lowercase()}\"") }
          }
          append("}")
        }
      },
    )
    append("]}")
  }

  // ---------------------------------------------------------------------------------------------
  // The editor's canvas (ED0, docs/ED0_SPIKE.md): an interpreter from a recognised document node to
  // the generated guest stubs, so the canvas draws through the generated renderers as a device does.

  /**
   * `portal-compose-render`'s Generated.kt: one branch per widget overload and per modifier, each
   * calling the guest stub with the node's arguments and, for an argument the node does not set,
   * the stub's own default expression (copied, as the stub copies Compose's).
   */
  fun editorRender(pkg: String): Pair<String, String> {
    val imports = sortedSetOf<String>()
    val body = StringBuilder()
    body.append("/** Calls the guest stub for a widget node of [type] (`<guest fq>#<tag>`); false when the type is not generated here. */\n")
    body.append("@Composable\ninternal fun renderGenerated(type: String, a: CanvasArgs, modifier: Modifier, slots: CanvasSlots): Boolean {\n")
    body.append("  when (type) {\n")
    for (w in widgets) {
      // A lazy list's content is a LazyListScope block, not a slot: the canvas does not draw it yet
      // (renderGenerated says false, and the canvas reports the node instead of guessing).
      if (w.params.any { it.kind == ParamKind.LAZY }) continue
      val d = w.decl
      currentDecl = d
      body.append("    \"${d.mirrorPkg}.${d.name}#${w.entry.tag}\" -> {\n")
      val args = mutableListOf<String>()
      for (c in w.params) {
        val n = c.param.name
        val t = c.param.type
        when (c.kind) {
          ParamKind.MODIFIER -> args += "$n = modifier"
          ParamKind.SLOT -> args += "$n = { slots.Render(\"$n\", ${if (t.receiver != null) "this" else "null"}) }"
          ParamKind.EVENT -> args += "$n = a.action${t.functionParams.size}(\"$n\")"
          ParamKind.VALUE -> {
            body.append("      val $n = ${canvasValue(c, d, imports, missing = "return a.missing(\"$n\")")}\n")
            args += "$n = $n"
          }
          else -> {}
        }
      }
      body.append("      ${d.mirrorPkg}.${d.name}(\n")
      args.forEach { body.append("        $it,\n") }
      body.append("      )\n    }\n")
    }
    body.append("    else -> return false\n  }\n  return true\n}\n\n")

    body.append("/** Appends the modifier element [key] (`<name>#<tag>`) to [m]; null when it is not generated here, misses an argument or its scope. */\n")
    body.append("@Composable\ninternal fun applyGenerated(m: Modifier, key: String, a: CanvasArgs, scope: Any?): Modifier? {\n  return when (key) {\n")
    for (mod in modifiers) {
      val d = mod.decl
      currentDecl = d
      val locals = mutableListOf<String>()
      val args = mutableListOf<String>()
      for (c in mod.params) {
        val n = c.param.name
        when (c.kind) {
          ParamKind.VALUE -> {
            locals += "val $n = ${canvasValue(c, d, imports, missing = "return null")}"
            args += "$n = $n"
          }
          ParamKind.EVENT -> args += "$n = a.action${c.param.type.functionParams.size}(\"$n\")"
          else -> {}
        }
      }
      val call = "m.${d.name}(${args.joinToString(", ")})"
      val guarded = if (d.owner == null) {
        imports += "${d.mirrorPkg}.${d.name}"
        call
      } else {
        "(scope as? ${mirrorPackage(d.pkg)}.${d.owner})?.run { $call }"
      }
      val text = if (locals.isEmpty()) guarded else "run { ${locals.joinToString("; ")}; $guarded }"
      body.append("    \"${d.name}#${mod.entry.tag}\" -> $text\n")
    }
    body.append("    else -> null\n  }\n}\n")

    val text = buildString {
      append(HEADER)
      append("@file:Suppress(\"ktlint\", \"RedundantVisibilityModifier\", \"DEPRECATION\", \"UNUSED_VARIABLE\")\n\n")
      append("package $pkg\n\n")
      (listOf("androidx.compose.runtime.Composable", "dev.keliver.compose.ui.Modifier") + imports).distinct().sorted().forEach { append("import $it\n") }
      append('\n').append(body)
    }
    return "${pkg.replace('.', '/')}/Generated.kt" to text
  }

  /**
   * A value argument as the canvas reads it from a node: the node's value when it sets one, else
   * the stub's default. A required argument the node lacks ends the branch ([CanvasArgs.missing]).
   */
  private fun canvasValue(c: Classified, d: DeclInfo, imports: MutableSet<String>, missing: String): String {
    val t = c.param.type
    val n = c.param.name
    val default = c.param.defaultText
    // A host-state handle that travels as its wire value (`LazyListState`) is never a document
    // value: the canvas always takes the stub's default (a fresh state), as a new screen does.
    // So is an animation spec (Gate B-e): the canvas draws the start state, with the stub's default.
    if (t.fq in TypeMap.wireValue || t.fq in TypeMap.generic) {
      if (default == null) return missing
      imports += expressionImports(default, d, mirror = true)
      return "($default)"
    }
    val read = when {
      t.fq == TypeMap.IMAGE_MODEL -> "a.string(\"$n\")"
      t.fq == "kotlin.String" -> "a.string(\"$n\")"
      t.fq == "kotlin.Int" -> "a.int(\"$n\")"
      t.fq == "kotlin.Boolean" -> "a.bool(\"$n\")"
      t.fq == "kotlin.Float" -> "a.float(\"$n\")"
      // A type only a `*Defaults` factory makes (`ButtonColors`): its generated class's own codec.
      t.fq in TypeMap.opaque -> "a.value(\"$n\", ${mirrorFq(t.fq)}.Codec)"
      else -> "a.value(\"$n\", ${codecFq(mirrorFq(t.fq))})"
    }
    return when {
      default == null -> if (t.nullable) read else "$read ?: $missing"
      else -> {
        imports += expressionImports(default, d, mirror = true)
        if (t.nullable) "if (a.has(\"$n\")) $read else ($default)" else "$read ?: ($default)"
      }
    }
  }
}

/**
 * The hand-written codec of a mirror type (keliver-compose-values): `<Simple>Codec` beside it, or
 * `<Inner><Outer>Codec` for a nested type (`Alignment.Horizontal` → `HorizontalAlignmentCodec`).
 */
fun codecFq(mirror: String): String {
  val pkg = packageOf(mirror)
  val classes = mirror.removePrefix("$pkg.").split('.')
  return "$pkg." + (if (classes.size == 2) classes[1] + classes[0] else classes.last()) + "Codec"
}

fun kotlinString(s: String): String = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
fun jsonString(s: String): String = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
