package dev.keliver.compose.generator

import java.io.File
import kotlin.test.Test
import kotlin.test.assertTrue

/**
 * Spike (docs/COMPOSE_GENERIC_MECHANISMS.md, part b): the generic emitters' output, from the real
 * Compose metadata and sources, carries each mechanism's rules. (The spike module that
 * checked the output in and ran it against a real Compose host stays on #312's branch.)
 */
class GenericEmitTest {
  private val generated by lazy {
    GenericSpike.generate(
      (System.getProperty("keliver.composeApi") ?: error("the test task passes keliver.composeApi")).split(File.pathSeparator).map(::File),
      (System.getProperty("keliver.composeSources") ?: error("the test task passes keliver.composeSources")).split(File.pathSeparator).map(::File),
    ).first
  }

  @Test fun callRecords() {
    val guest = generated.getValue("dev/keliver/spike/compose/ui/text/GeneratedCalls.kt")
    // A defaulted parameter: nullable, left out of the wire when not passed.
    assertTrue("  fontSize: dev.keliver.compose.ui.unit.TextUnit? = null," in guest)
    // A computed or constructor-backed read on a recorded value is a compile-time error.
    assertTrue("public val fontSize: Nothing" in guest)
    val host = generated.getValue("dev/keliver/spike/host/GeneratedReplay.kt")
    // Compose's default expression, copied from its sources and qualified, evaluated on the host.
    assertTrue("?: (androidx.compose.ui.geometry.Offset.Infinite)" in host)
    // A companion constant the default names unqualified (`DefaultMiter` in Stroke).
    assertTrue("androidx.compose.ui.graphics.drawscope.Stroke.DefaultMiter" in host)
  }

  @Test fun remoteObject() {
    val guest = generated.getValue("dev/keliver/spike/compose/foundation/pager/GeneratedRemote.kt")
    assertTrue("public val currentPage: kotlin.Int get() = remote.read(\"currentPage\")" in guest)
    assertTrue("public suspend fun animateScrollToPage(page: kotlin.Int, pageOffsetFraction: kotlin.Float? = null)" in guest)
    // A synchronous result and a lambda argument cannot cross: error stubs.
    assertTrue("`PagerState.dispatchRawDelta(delta)` does not cross the bridge (a synchronous result)" in guest)
    assertTrue("`PagerState.scroll(scrollPriority,block)` does not cross the bridge (an argument type)" in guest)
  }

  @Test fun recordedInterface() {
    val host = generated.getValue("dev/keliver/spike/host/GeneratedDrawReplay.kt")
    // A default naming a sibling parameter and a private member: a presence split, not a copy.
    assertTrue("\"drawRect(color,topLeft,size,alpha,style,colorFilter,blendMode)\" -> if (\"size\" in a) drawRect(" in host)
    // A default that reads the scope (`this.center`) is evaluated on the host's real scope.
    assertTrue("?: (this.center)" in host)
  }
}
