package dev.keliver.portal.codegen

// P3: the interpreter reads through the *B getters (portal-render), which
// resolve Bind values against PreviewBindings.mocks before falling back.
internal fun getterExpr(p: MappedProp): String = when (p.kind) {
  MappedKind.TEXT -> {
    val d = defaultString(p.defaultExpr).replace("\\", "\\\\").replace("\"", "\\\"")
    if (d.isEmpty()) "node.strB(\"${p.name}\")" else "node.strB(\"${p.name}\", \"$d\")"
  }
  MappedKind.INT -> "node.intB(\"${p.name}\", ${defaultInt(p.defaultExpr)})"
  MappedKind.BOOL -> "node.boolB(\"${p.name}\", ${defaultBool(p.defaultExpr)})"
  MappedKind.DOUBLE -> "node.dblB(\"${p.name}\", ${defaultDouble(p.defaultExpr)})"
  MappedKind.FLOAT -> "node.dblB(\"${p.name}\", ${defaultDouble(p.defaultExpr)}).toFloat()"
  MappedKind.INT_LIST -> "node.intList(\"${p.name}\")"
  MappedKind.FLOAT_LIST -> "node.floatList(\"${p.name}\")"
  MappedKind.STRING_LIST -> "node.strList(\"${p.name}\")"
  // Dp rejects negatives (init require): clamp so a mid-edit "-" can't crash the preview.
  MappedKind.DP -> "Dp(node.dblB(\"${p.name}\", ${defaultDouble(p.defaultExpr?.removePrefix("Dp(")?.removeSuffix(")"))}).coerceAtLeast(0.0))"
  MappedKind.CONSTRAINT -> "constraintOf(node.intB(\"${p.name}\", ${constraintDefault(p.defaultExpr)}))"
  MappedKind.CROSS_AXIS -> "crossAxisOf(node.intB(\"${p.name}\", ${crossAxisDefault(p.defaultExpr)}))"
  MappedKind.MAIN_AXIS -> "mainAxisOf(node.intB(\"${p.name}\", ${mainAxisDefault(p.defaultExpr)}))"
  MappedKind.OVERFLOW -> "overflowOf(node.intB(\"${p.name}\", ${overflowDefault(p.defaultExpr)}))"
  // Every schema Margin defaults to Margin.Zero, which is what absent sides give.
  MappedKind.MARGIN -> "marginOf(node, \"${p.name}\")"
}

/** Lambda wiring for a nullable event prop holding an Action. */
internal fun eventExpr(e: EventPlan): String {
  val lambda = when (e.paramCount) {
    0 -> "{ PreviewBindings.fire(a) }"
    1 -> "{ value -> PreviewBindings.fire(a, value) }"
    else -> "{ ${List(e.paramCount) { "_" }.joinToString(", ")} -> PreviewBindings.fire(a) }"
  }
  return "node.actionOf(\"${e.name}\")?.let { a -> $lambda }"
}

fun emitRenderNode(widgets: List<WidgetPlan.Include>, modifiers: List<ModPlan> = emptyList()): String = buildString {
  val sorted = widgets.sortedBy { it.name }
  val mods = modifiers.sortedBy { it.name }
  val unscoped = mods.filter { !it.isScoped }
  // scope simple name ("RowScope") -> its compose interface's package, first-seen order by name.
  val scopes = mods.filter { it.isScoped }
    .flatMap { m -> m.scopes.map { it to m.composePackage } }
    .distinctBy { it.first }
    .sortedBy { it.first }
  appendLine("// GENERATED by :portal-schema-codegen — do not edit. Run ./gradlew :portal-schema-codegen:generatePortalCode")
  appendLine("package dev.keliver.portal.render")
  appendLine()
  appendLine("import androidx.compose.runtime.Composable")
  if (mods.isNotEmpty()) appendLine("import dev.keliver.Modifier")
  for ((scope, pkg) in scopes) appendLine("import $pkg.$scope")
  appendLine("import dev.keliver.portal.WidgetNode")
  appendLine("import dev.keliver.portal.bool")
  appendLine("import dev.keliver.portal.floatList")
  appendLine("import dev.keliver.portal.intList")
  appendLine("import dev.keliver.portal.strList")
  val usesDp = sorted.any { w -> w.props.any { it.kind == MappedKind.DP } } ||
    mods.any { m -> m.props.any { it.kind == MappedKind.DP } }
  if (usesDp) appendLine("import dev.keliver.ui.Dp")
  for (w in sorted) appendLine("import ${w.composePackage}.${w.name}")
  // Scoped modifiers are members of their scope interfaces: applied with(scope), never imported.
  for (m in unscoped) appendLine("import ${m.composePackage}.${m.extensionName}")
  appendLine()
  appendLine("/** Interprets a portal WidgetNode tree as live keliver composables. */")
  appendLine("@Composable")
  appendLine("public fun RenderNode(node: WidgetNode) {")
  appendLine("  RenderNode(node, null)")
  appendLine("}")
  appendLine()
  appendLine("/**")
  appendLine(" * K1: [scope] is the content-lambda receiver of the node's layout parent")
  appendLine(" * (RowScope/ColumnScope/BoxScope), or null. Scoped layout modifiers (flex,")
  appendLine(" * margin, …) only apply with the right receiver — exactly as on a device.")
  appendLine(" */")
  appendLine("@Composable")
  appendLine("public fun RenderNode(node: WidgetNode, scope: Any?) {")
  appendLine("  when (node.type) {")
  // M5/P2: Condition honors a boolean mock (default shown); Repeat renders
  // rowCount() mock rows with item binds resolved per row.
  //
  // FIDELITY: neither emits a wrapper container. On a DEVICE these logic nodes
  // do not exist at runtime — the guest runs the real `if` / `forEach`, so the
  // children land directly in the enclosing layout. A wrapper Column here would
  // default to wrap-content and silently shrink children that fill their parent
  // (observed: Repeat-generated ListItems stopped short of the card width on web
  // while filling on Android/iOS). Emitting straight into the parent slot keeps
  // the preview structurally identical to the device — including the parent's
  // scope, which passes straight through.
  appendLine("    \"Condition\" -> {")
  appendLine("      val field = (node.props[\"field\"] as? String) ?: \"\"")
  appendLine("      if (PreviewBindings.mocks[field]?.toBooleanStrictOrNull() != false) {")
  appendLine("        node.children.forEach { RenderNode(it, scope) }")
  appendLine("      }")
  appendLine("    }")
  appendLine("    \"Repeat\" -> {")
  appendLine("      val itemVar = (node.props[\"item\"] as? String) ?: \"item\"")
  appendLine("      val itemsField = (node.props[\"items\"] as? String) ?: \"items\"")
  appendLine("      repeat(PreviewBindings.rowCount(itemsField)) { i ->")
  appendLine("        node.children.forEach { RenderNode(PreviewBindings.mockItemRow(it, itemVar, itemsField, i), scope) }")
  appendLine("      }")
  appendLine("    }")
  for (w in sorted) {
    appendLine("    \"${w.name}\" -> ${w.name}(")
    if (mods.isNotEmpty()) appendLine("      modifier = nodeModifier(node, scope),")
    for (p in w.props) appendLine("      ${p.name} = ${getterExpr(p)},")
    for (e in w.events) appendLine("      ${e.name} = ${eventExpr(e)},")
    append("    )")
    if (w.hasChildren) {
      val childScope = if (w.childScope != null) "this" else "null"
      append(" { node.children.forEach { RenderNode(it, $childScope) } }")
    }
    appendLine()
  }
  // C1: an unrecognized type is a project-component instance — the editor sets
  // `componentPreviewInScope` (or the older `componentPreview`) to expand it
  // transparently (or render an opaque/cycle placeholder). Devices never hit
  // this path (they call the real composable).
  appendLine("    else -> componentPreviewInScope?.invoke(node, scope) ?: componentPreview?.invoke(node)")
  appendLine("      ?: StyledText(text = \"\\u26a0 unknown widget: \${node.type}\", colorArgb = -5238254)")
  appendLine("  }")
  appendLine("}")
  if (mods.isNotEmpty()) {
    appendLine()
    appendLine("/**")
    appendLine(" * Builds the Modifier chain from a node's namespaced \"mod.*\" props in AUTHOR")
    appendLine(" * order (the order the document keeps, as the device's chain does). A scoped")
    appendLine(" * layout modifier applies with(scope) of the parent's content lambda, and is")
    appendLine(" * skipped when [scope] is not one of its scopes (it has no meaning there).")
    appendLine(" */")
    appendLine("private fun nodeModifier(node: WidgetNode, scope: Any?): Modifier {")
    appendLine("  var m: Modifier = Modifier")
    appendLine("  val names = node.props.keys.filter { it.startsWith(\"mod.\") }.map { it.removePrefix(\"mod.\").substringBefore('.') }.distinct()")
    appendLine("  for (name in names) {")
    appendLine("    m = when (name) {")
    for (mod in mods) {
      if (!mod.isScoped) {
        appendLine("      \"${mod.name}\" -> ${applyExpr(mod)}")
      } else {
        appendLine("      \"${mod.name}\" -> when (scope) {")
        for (sc in mod.scopes.sorted()) appendLine("        is $sc -> with(scope) { ${applyExpr(mod)} }")
        appendLine("        else -> m")
        appendLine("      }")
      }
    }
    appendLine("      else -> m")
    appendLine("    }")
    appendLine("  }")
    appendLine("  return m")
    appendLine("}")
  }
}

private fun applyExpr(mod: ModPlan): String =
  if (mod.props.isEmpty()) {
    "if (node.bool(\"mod.${mod.name}\")) m.${mod.extensionName}() else m"
  } else {
    val args = mod.props.joinToString(", ") { p -> getterExpr(p.copy(name = "mod.${mod.name}.${p.name}")) }
    "m.${mod.extensionName}($args)"
  }
