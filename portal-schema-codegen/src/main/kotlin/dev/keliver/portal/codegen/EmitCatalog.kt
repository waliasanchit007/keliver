package dev.keliver.portal.codegen

internal fun catalogKind(p: MappedProp): String = when {
  p.isColor -> "Color"
  else -> when (p.kind) {
    MappedKind.TEXT -> "Text"
    MappedKind.INT, MappedKind.CONSTRAINT, MappedKind.CROSS_AXIS, MappedKind.MAIN_AXIS, MappedKind.OVERFLOW -> "Int"
    MappedKind.BOOL -> "Bool"
    MappedKind.DOUBLE, MappedKind.FLOAT, MappedKind.DP, MappedKind.MARGIN -> "Double"
    MappedKind.INT_LIST -> "IntList"
    MappedKind.FLOAT_LIST -> "FloatList"
    MappedKind.STRING_LIST -> "StringList"
  }
}

/**
 * The catalog PropSpec lines for [p]: one, or — for a MARGIN — four Double
 * specs `<prop>.start/.end/.top/.bottom` so the existing number editor works.
 */
internal fun propSpecs(p: MappedProp): List<String> =
  if (p.kind == MappedKind.MARGIN) {
    MARGIN_SIDES.map { side ->
      "PropSpec(\"${p.name}.$side\", PropKind.Double, \"${humanize(p.name)} $side\")"
    }
  } else {
    listOf("PropSpec(\"${p.name}\", PropKind.${catalogKind(p)}, \"${humanize(p.name)}\")")
  }

/** camelCase → "Camel case" */
internal fun humanize(name: String): String {
  val words = name.replace(Regex("([a-z0-9])([A-Z])"), "$1 $2").lowercase()
  return words.replaceFirstChar { it.uppercase() }
}

private fun sampleValue(widgetName: String, p: MappedProp): String? = when {
  !p.required -> null
  else -> when (p.kind) {
    MappedKind.TEXT -> "\"New $widgetName\""
    MappedKind.INT, MappedKind.CONSTRAINT, MappedKind.CROSS_AXIS, MappedKind.MAIN_AXIS, MappedKind.OVERFLOW -> "0"
    MappedKind.BOOL -> "false"
    MappedKind.DOUBLE, MappedKind.FLOAT, MappedKind.DP -> "0.0"
    MappedKind.INT_LIST -> "listOf<Int>()"
    MappedKind.FLOAT_LIST -> "listOf<Float>()"
    MappedKind.STRING_LIST -> "listOf(\"Option A\", \"Option B\")"
    MappedKind.MARGIN -> null // always defaulted (Margin.Zero) in the schemas
  }
}

fun emitCatalog(widgets: List<WidgetPlan.Include>, modifiers: List<ModPlan> = emptyList()): String = buildString {
  appendLine("// GENERATED by :portal-schema-codegen — do not edit. Run ./gradlew :portal-schema-codegen:generatePortalCode")
  appendLine("package dev.keliver.portal")
  appendLine()
  appendLine("public val widgetSpecs: List<WidgetSpec> = listOf(")
  for (w in widgets.sortedBy { it.name }) {
    append("  WidgetSpec(\"${w.name}\", \"${w.category}\", listOf(")
    if (w.props.isNotEmpty()) {
      appendLine()
      for (p in w.props) {
        for (line in propSpecs(p)) appendLine("    $line,")
      }
      append("  )")
    } else {
      append(")")
    }
    append(", acceptsChildren = ${w.hasChildren}, sampleProps = ")
    val samples = w.props.mapNotNull { p -> sampleValue(w.name, p)?.let { "\"${p.name}\" to $it" } }
    if (samples.isEmpty()) append("emptyMap()") else append("mapOf(${samples.joinToString(", ")})")
    if (w.events.isNotEmpty()) append(", events = listOf(${w.events.joinToString(", ") { "\"${it.name}\"" }})")
    appendLine("),")
  }
  // M5: logic nodes (not schema widgets) — portal-editable control flow.
  appendLine("""  WidgetSpec("Condition", "Logic", listOf(PropSpec("field", PropKind.Text, "If field (Boolean)")), acceptsChildren = true, sampleProps = mapOf("field" to "showThis")),""")
  appendLine("""  WidgetSpec("Repeat", "Logic", listOf(PropSpec("items", PropKind.Text, "Items field (List)"), PropSpec("item", PropKind.Text, "Item name")), acceptsChildren = true, sampleProps = mapOf("items" to "items", "item" to "item")),""")
  appendLine(")")
  appendLine()
  appendLine("public val modifierSpecs: List<ModifierSpec> = listOf(")
  for (m in modifiers.sortedBy { it.name }) {
    append("  ModifierSpec(\"${m.name}\", listOf(")
    append(m.props.flatMap { propSpecs(it) }.joinToString(", "))
    append(")")
    if (m.isScoped) append(", scopes = listOf(${m.parentTypes.joinToString(", ") { "\"$it\"" }})")
    if (m.extensionName != m.name.replaceFirstChar { it.lowercase() }) append(", extension = \"${m.extensionName}\"")
    if (m.props.isNotEmpty()) append(", argTypes = listOf(${m.props.joinToString(", ") { "\"${sourceType(it.kind)}\"" }})")
    appendLine("),")
  }
  appendLine(")")
  appendLine()
  // K1: every wire key that holds a Dp (Dp props, Margin sides, Dp/Margin
  // modifier args) — Dp is non-negative, so these clamp at 0 everywhere.
  val dpKeys = buildList {
    for (w in widgets.sortedBy { it.name }) for (p in w.props) {
      if (p.kind == MappedKind.DP || p.kind == MappedKind.MARGIN) wireKeys(p.name, p.kind).forEach { add("${w.name}.$it") }
    }
    for (m in modifiers.sortedBy { it.name }) for (p in m.props) {
      if (p.kind == MappedKind.DP || p.kind == MappedKind.MARGIN) wireKeys("mod.${m.name}.${p.name}", p.kind).forEach { add(it) }
    }
  }
  appendLine("/** Wire keys (\"Widget.prop\", \"mod.Modifier.prop\") holding a Dp — see isDpProp. */")
  appendLine("public val dpPropKeys: Set<String> = setOf(")
  for (k in dpKeys) appendLine("  \"$k\",")
  appendLine(")")
  appendLine()
  // K2: the Kotlin source type of every widget prop's wire key — a design-token
  // reference is grammar only where the source takes a plain literal of the
  // token's own type (an Int constant fits `Int`, not `Constraint` or `Dp`).
  appendLine("/** \"Widget.prop\" wire key -> its Kotlin source type (\"Int\", \"Dp\", \"Constraint\", …) — see propSourceType. */")
  appendLine("internal val widgetPropSourceTypes: Map<String, String> = mapOf(")
  for (w in widgets.sortedBy { it.name }) for (p in w.props) {
    val type = if (p.kind == MappedKind.MARGIN) "Dp" else sourceType(p.kind)
    for (k in wireKeys(p.name, p.kind)) appendLine("  \"${w.name}.$k\" to \"$type\",")
  }
  appendLine(")")
  appendLine()
  appendLine("private val specsByType = widgetSpecs.associateBy { it.type }")
  appendLine()
  appendLine("public fun widgetSpec(type: String): WidgetSpec? = specsByType[type]")
  appendLine()
  appendLine("public fun editableProps(type: String): List<PropSpec> = specsByType[type]?.props ?: emptyList()")
}
