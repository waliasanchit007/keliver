package dev.keliver.bridge.codegen

import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.INT
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.LambdaTypeName
import com.squareup.kotlinpoet.ParameterSpec
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.STRING
import com.squareup.kotlinpoet.TypeSpec
import com.squareup.kotlinpoet.UNIT

/**
 * Writes `<Name>Bridge.kt` for one [Bridge], in its package (`docs/BRIDGE_CODEGEN_DESIGN.md`,
 * section 4): `<Name>Service`, `<Name>Callbacks`, `<Name>Bridge`, and the internal classes
 * `bind` and `take` use. The rules of a call (its context, its limit, the first answer winning,
 * failures) are keliver-bridge's `BridgeGuard`, not generated code.
 */
internal class BridgeEmitter(private val bridge: Bridge) {
  private val packageName = bridge.className.packageName
  private val simpleName = bridge.className.simpleName
  private val service = ClassName(packageName, "${simpleName}Service")
  private val callbacks = ClassName(packageName, "${simpleName}Callbacks")
  private val bridgeObject = ClassName(packageName, "${simpleName}Bridge")
  private val guarded = ClassName(packageName, "${simpleName}GuardedService")
  private val callbackAdapter = ClassName(packageName, "${simpleName}CallbackAdapter")
  private val taken = ClassName(packageName, "${simpleName}Taken")

  fun file(): FileSpec = FileSpec.builder(packageName, "${simpleName}Bridge")
    .addFileComment("Generated by keliver-bridge-codegen from %L. Do not edit.", bridge.className.canonicalName)
    .addType(serviceInterface())
    .addType(callbacksInterface())
    .addType(bridgeObject())
    .addType(guardedService())
    .addType(callbackAdapter())
    .addType(takenWrapper())
    .build()

  private fun serviceInterface() = TypeSpec.interfaceBuilder(service)
    .addKdoc("[%T] across Zipline, bound and taken by [%T]. Only the generated code uses it.", bridge.className, bridgeObject)
    .addSuperinterface(ZIPLINE_SERVICE)
    .addFunctions(bridge.functions.map { function(it, KModifier.ABSTRACT).build() })
    .build()

  private fun callbacksInterface() = TypeSpec.interfaceBuilder(callbacks)
    .addKdoc(
      "[%T] for an iOS app, which implements it in Swift (Kotlin/Native exports it as a protocol). " +
        "Each call answers once, with `done` or `fail`; `call` says when the guest stopped waiting. " +
        "A fire-and-forget function has neither. Pass it to [%T.bind].",
      bridge.className,
      bridgeObject,
    )
    .addFunctions(
      bridge.functions.map { function ->
        FunSpec.builder(function.name)
          .addModifiers(KModifier.ABSTRACT)
          .addParameters(function.parameters.map { ParameterSpec(it.name, it.type) })
          .apply {
            if (function.suspending) {
              addParameter("call", BRIDGE_CALL)
              addParameter("done", LambdaTypeName.get(parameters = listOfNotNull(function.returnType).toTypedArray(), returnType = UNIT))
              addParameter("fail", LambdaTypeName.get(parameters = arrayOf(STRING), returnType = UNIT))
            }
          }
          .build()
      },
    )
    .build()

  private fun bridgeObject(): TypeSpec {
    val context = ParameterSpec.builder("context", COROUTINE_CONTEXT).defaultValue("%T.Default", DISPATCHERS).build()
    val log = ParameterSpec.builder("log", LambdaTypeName.get(parameters = arrayOf(STRING), returnType = UNIT)).defaultValue("{}").build()
    return TypeSpec.objectBuilder(bridgeObject)
      .addKdoc("Binds [%T] in a host and takes it in the guest, under [NAME].", bridge.className)
      .addProperty(PropertySpec.builder("NAME", STRING, KModifier.CONST).initializer("%S", bridge.name).build())
      .addProperty(PropertySpec.builder("VERSION", INT, KModifier.CONST).initializer("%L", bridge.version).build())
      .addProperty(
        PropertySpec.builder("SHAPE", STRING, KModifier.CONST)
          .addKdoc("A hash of the functions and of the types they reach, for the compatibility gate (B4).")
          .initializer("%S", bridge.shape.hash)
          .build(),
      )
      .addFunction(
        FunSpec.builder("bind")
          .addKdoc("Host side: serves the guest's calls with [impl], each on [context] and through the guard.")
          .addParameter("zipline", ZIPLINE)
          .addParameter("impl", bridge.className)
          .addParameter(context)
          .addParameter(log)
          .addStatement("zipline.bind<%T>(NAME, %T(impl, %T(NAME, context, log)))", service, guarded, BRIDGE_GUARD)
          .build(),
      )
      .addFunction(
        FunSpec.builder("bind")
          .addKdoc(
            "Host side, for an iOS app: serves the guest's calls with Swift's [callbacks], each on [context] and through the guard. " +
              "Pass `Dispatchers.Main`: Swift's code expects the main thread, so there is no default.",
          )
          .addParameter("zipline", ZIPLINE)
          .addParameter("callbacks", callbacks)
          .addParameter("context", COROUTINE_CONTEXT)
          .addParameter(log)
          .addStatement("zipline.bind<%T>(NAME, %T(callbacks, %T(NAME, context, log)))", service, callbackAdapter, BRIDGE_GUARD)
          .build(),
      )
      .addFunction(
        FunSpec.builder("take")
          .addKdoc("Guest side: the host's [%T]. A failed call throws `BridgeCallFailed`.", bridge.className)
          .addParameter("zipline", ZIPLINE)
          .returns(bridge.className)
          .addStatement("return %T(zipline.take<%T>(NAME))", taken, service)
          .build(),
      )
      .build()
  }

  private fun guardedService() = TypeSpec.classBuilder(guarded)
    .addModifiers(KModifier.INTERNAL)
    .addKdoc("Serves each call with the app's [%T] through the guard.", bridge.className)
    .primaryConstructor(
      FunSpec.constructorBuilder()
        .addParameter("impl", bridge.className)
        .addParameter("guard", BRIDGE_GUARD)
        .build(),
    )
    .addProperty(PropertySpec.builder("impl", bridge.className, KModifier.PRIVATE).initializer("impl").build())
    .addProperty(PropertySpec.builder("guard", BRIDGE_GUARD, KModifier.PRIVATE).initializer("guard").build())
    .addSuperinterface(service)
    .addFunctions(
      bridge.functions.map { function ->
        val call = CodeBlock.of("impl.%L(%L)", function.name, arguments(function))
        function(function, KModifier.OVERRIDE)
          .apply {
            if (function.suspending) {
              addStatement("return guard.call(%S, %L) { %L }", function.name, function.timeoutSeconds, call)
            } else {
              addStatement("guard.post(%S) { %L }", function.name, call)
            }
          }
          .build()
      },
    )
    .build()

  private fun callbackAdapter() = TypeSpec.classBuilder(callbackAdapter)
    .addModifiers(KModifier.INTERNAL)
    .addKdoc("Connects Swift's [%T] to the guard, which owns `call`, `done` and `fail`.", callbacks)
    .primaryConstructor(
      FunSpec.constructorBuilder()
        .addParameter("callbacks", callbacks)
        .addParameter("guard", BRIDGE_GUARD)
        .build(),
    )
    .addProperty(PropertySpec.builder("callbacks", callbacks, KModifier.PRIVATE).initializer("callbacks").build())
    .addProperty(PropertySpec.builder("guard", BRIDGE_GUARD, KModifier.PRIVATE).initializer("guard").build())
    .addSuperinterface(service)
    .addFunctions(
      bridge.functions.map { function ->
        val arguments = arguments(function)
        function(function, KModifier.OVERRIDE)
          .apply {
            when {
              !function.suspending -> addStatement("guard.post(%S) { callbacks.%L(%L) }", function.name, function.name, arguments)
              function.returnType == null -> addStatement(
                "return guard.callback<Unit>(%S, %L) { call, done, fail -> callbacks.%L(%L) }",
                function.name,
                function.timeoutSeconds,
                function.name,
                join(arguments, "call", "{ done(Unit) }", "fail"),
              )
              else -> addStatement(
                "return guard.callback(%S, %L) { call, done, fail -> callbacks.%L(%L) }",
                function.name,
                function.timeoutSeconds,
                function.name,
                join(arguments, "call", "done", "fail"),
              )
            }
          }
          .build()
      },
    )
    .build()

  private fun takenWrapper() = TypeSpec.classBuilder(taken)
    .addModifiers(KModifier.INTERNAL)
    .addKdoc(
      "The guest's [%T]: a host's failure arrives as a `ZiplineException` carrying its text, and is thrown again as the `BridgeCallFailed` it was.",
      bridge.className,
    )
    .primaryConstructor(FunSpec.constructorBuilder().addParameter("service", service).build())
    .addProperty(PropertySpec.builder("service", service, KModifier.PRIVATE).initializer("service").build())
    .addSuperinterface(bridge.className)
    .addFunctions(
      bridge.functions.map { function ->
        val call = CodeBlock.of("service.%L(%L)", function.name, arguments(function))
        function(function, KModifier.OVERRIDE)
          .apply {
            if (function.suspending) {
              beginControlFlow("try")
              addStatement(if (function.returnType == null) "%L" else "return %L", call)
              nextControlFlow("catch (e: %T)", ZIPLINE_EXCEPTION)
              addStatement("throw %T.fromZiplineMessage(e.message) ?: e", BRIDGE_CALL_FAILED)
              endControlFlow()
            } else {
              addStatement("%L", call)
            }
          }
          .build()
      },
    )
    .build()

  private fun function(function: BridgeFunction, modifier: KModifier) = FunSpec.builder(function.name)
    .addModifiers(modifier)
    .apply { if (function.suspending) addModifiers(KModifier.SUSPEND) }
    .addParameters(function.parameters.map { ParameterSpec(it.name, it.type) })
    .apply { function.returnType?.let(::returns) }

  private fun arguments(function: BridgeFunction): String = function.parameters.joinToString(", ") { it.name }

  private fun join(vararg parts: String): String = parts.filter { it.isNotEmpty() }.joinToString(", ")

  private companion object {
    val ZIPLINE = ClassName("app.cash.zipline", "Zipline")
    val ZIPLINE_SERVICE = ClassName("app.cash.zipline", "ZiplineService")
    val ZIPLINE_EXCEPTION = ClassName("app.cash.zipline", "ZiplineException")
    val BRIDGE_GUARD = ClassName("dev.keliver.bridge", "BridgeGuard")
    val BRIDGE_CALL = ClassName("dev.keliver.bridge", "BridgeCall")
    val BRIDGE_CALL_FAILED = ClassName("dev.keliver.bridge", "BridgeCallFailed")
    val COROUTINE_CONTEXT = ClassName("kotlin.coroutines", "CoroutineContext")
    val DISPATCHERS = ClassName("kotlinx.coroutines", "Dispatchers")
  }
}
